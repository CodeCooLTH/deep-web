-- feature 00047 — สลับภาษาไทย/อังกฤษในแอปผู้ขาย
--
-- locale: ภาษาของหน้าจอสำหรับผู้ใช้คนนั้น "th" | "en"
--   th = ภาษาไทย (ค่าตั้งต้น พฤติกรรมเดิมทั้งหมดก่อนฟีเจอร์นี้)
--   en = ภาษาอังกฤษ
--
-- ที่มา: Meta ตีกลับ App Review 2026-08-13 และระบุ best practice ว่าให้ใช้ภาษาอังกฤษเป็น
-- ภาษาของส่วนติดต่อผู้ใช้ในคลิปที่ส่งให้ตรวจ (docs/20 - Features/00047 - Bilingual UI/PRD.md)
--
-- เก็บที่ "User" ไม่ใช่ "Shop" — เป็นวิธีทำงานของคน ไม่ใช่การตั้งค่าของร้าน คนคนเดียวสลับไป
-- ร้านไหนก็อยากอ่านภาษาเดิมของตัวเอง (เหตุผลเดียวกับ chatScopeMode ของ 00037 เป๊ะ)
--
-- 🛑 คอลัมน์นี้คือแหล่งความจริงเดียวของภาษา — cookie `deep_locale` เป็นเพียงเงาที่มีไว้ให้
--    หน้าที่ยังไม่ล็อกอินอ่าน; มี session เมื่อไหร่คอลัมน์นี้ชนะเสมอ (มติ D-I18N-6)
--
-- DEFAULT 'th' ทำให้แถวเดิมทุกแถวได้ค่าที่แปลว่า "เหมือนเดิม" ทันที — ไม่ต้อง backfill และ
-- ไม่มีช่วงเวลาที่ผู้ขายไทยเห็นหน้าจอเปลี่ยนภาษาโดยไม่ได้เลือกเอง (BR-I18N-01)
--
-- 🛑 ไม่มี CHECK constraint รายชื่อค่าโดยตั้งใจ — docs/conventions/migration-check-constraint-additive.md
--    (migration ที่แก้ CHECK แบบรายชื่อเคยลบค่าของกันเองเงียบ ๆ เมื่อสอง branch แก้พร้อมกัน)
--    ค่าที่ไม่รู้จักถูกกันที่ Valibot ขาเขียน และถูกตีเป็น 'th' ขาอ่าน (toLocale(), fail-closed)
--
-- additive ล้วน: เพิ่ม 1 คอลัมน์ ไม่มี backfill ไม่มี index ใหม่ ไม่แตะ constraint เดิม
ALTER TABLE "User" ADD COLUMN IF NOT EXISTS "locale" TEXT NOT NULL DEFAULT 'th';
