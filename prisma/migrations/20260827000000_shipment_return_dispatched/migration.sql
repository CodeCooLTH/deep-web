-- feature 00056 ต่อ — ขั้นที่ 3 ของแถบขากลับ: "ขนส่งกำลังนำพัสดุมาส่งคืนที่ร้าน"
--
-- ═══════════════════════════════════════════════════════════════════════════
-- ทำไมต้องมีคอลัมน์นี้ และทำไมถึงเลือกสัญญาณตัวนี้
-- ═══════════════════════════════════════════════════════════════════════════
--
-- user ถามว่าแถบขากลับ "ต้องมี 4 step ป่ะ" — คำตอบจากข้อมูลจริง (prod 2026-08-27):
--
--   iShip ส่ง **รหัสสถานะ** ของขากลับมาแค่ 2 ตัว (`return` / `return_success`)
--   ตรวจ event ทั้งหมดหลังพัสดุเริ่มตีกลับ (45 + 6 ครั้ง จาก 13 ใบ) ไม่มีรหัสอื่นเลย
--
-- ขั้นย่อยที่ละเอียดกว่านั้นอยู่ใน `statusDesc` ซึ่งเป็น **ข้อความอิสระ** — แต่ส่วนใหญ่
-- ใช้เป็นขั้นตอนไม่ได้ เพราะมันคือ *บันทึกเส้นทาง* ไม่ใช่ *ขั้น*:
--
--   TH065880509388 (SPX) เรียงตามเวลาจริง:
--     ถึงศูนย์คัดแยก → อยู่ระหว่างการขนส่ง → ถึงศูนย์คัดแยก → ถึงศูนย์คัดแยก
--     → ถึงศูนย์คัดแยก → กำลังนำส่งคืนผู้ส่ง → ถึงร้าน
--
--   "ถึงศูนย์คัดแยก" เกิด 4 ครั้งสลับกับ "อยู่ระหว่างการขนส่ง" ⇒ เอามาทำจุดบนแถบไม่ได้
--   (แถบต้องเดินหน้าอย่างเดียว ไม่ใช่วนกลับ)
--
-- 🛑 ตัวเดียวที่เดินหน้าอย่างเดียวจริง คือ **"กำลังนำส่งพัสดุคืนผู้ส่ง"**:
--   SPX 6 ใบ → เกิด **1 ครั้งพอดีทุกใบ** และเกิดก่อน `return_success` **1–4 ชม. ทุกใบ**
--   Flash 7 ใบ → **0 ครั้ง** (Flash ไม่ส่ง event สายนี้มาเลยแม้แต่ `return_success`)
--
-- ⇒ แถบจึงเป็น **4 จุดเมื่อขนส่งบอก · 3 จุดเมื่อไม่บอก** ตามหลักเดิมของฟีเจอร์นี้
--    ("จุดที่ไม่มีวันสว่าง = โกหกว่ายังไปไม่ถึง") ไม่ใช่ 4 จุดตายตัว
--
-- 🛑 **ความเปราะที่ต้องรู้ตัว:** สัญญาณนี้อ่านจากข้อความไทยอิสระของขนส่ง วันที่ SPX
--    เปลี่ยนคำ จุดนี้จะเลิกโผล่ **เงียบ ๆ ไม่มี error** — แต่ผลลัพธ์คือแถบถอยไปเป็น 3 จุด
--    ซึ่งยังถูกต้อง (degrade ปลอดภัย ไม่ใช่พัง) · มีเทส `[blocker]` ตรึงวลีไว้กับ SSOT

ALTER TABLE "OrderShipment" ADD COLUMN "returnDispatchedAt" TIMESTAMP(3);

-- ── backfill ────────────────────────────────────────────────────────────────
-- `MIN` = ครั้งแรกเสมอ (เหมือน returnStartedAt/returnedAt) ถึงแม้ข้อมูลจริงจะมีครั้งเดียว
-- ก็ตาม — ไม่พึ่งความบังเอิญของข้อมูลชุดปัจจุบัน
UPDATE "OrderShipment" AS s
SET "returnDispatchedAt" = agg.first_at
FROM (
    SELECT "shipmentId", MIN("occurredAt") AS first_at
    FROM "ShipmentEvent"
    WHERE "status" LIKE 'return%'
      AND "statusDesc" LIKE '%กำลังนำส่งพัสดุคืนผู้ส่ง%'
    GROUP BY "shipmentId"
) AS agg
WHERE s.id = agg."shipmentId";
