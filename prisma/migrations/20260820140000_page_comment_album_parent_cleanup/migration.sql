-- ## ที่มา
--
-- `ingestFeedComment` เคยตัดสินว่า "เป็น reply ไหม" ด้วย `parent_id !== post_id` พร้อมคอมเมนต์ว่า
-- "ยืนยันจาก payload จริง" ซึ่ง **จริงเฉพาะโพสต์รูปเดียว** — โพสต์อัลบั้ม Meta ส่ง `post_id` เป็น
-- สตอรีของ *รูปย่อย* แต่ `parent_id` เป็นสตอรีของ *อัลบั้มแม่* ⇒ คอมเมนต์ระดับบนถูกบันทึกเป็น
-- "reply ของคอมเมนต์ที่ไม่มีอยู่จริง" ⇒ หายจากเธรดทั้งใบ
-- (user เจอเองบน prod 2026-08-20 พร้อมภาพจาก Facebook ที่ยืนยันว่าเป็นคอมเมนต์ระดับบน)
--
-- ตัวจำแนกถูกแก้ไปแล้วที่ `src/lib/facebook-comment-parent.ts` (fb10cccc) และมีตาข่ายฝั่ง render
-- ที่ `comment-tree-visibility.ts` กันไม่ให้แถวหายอีก — **แต่ค่าที่ผิดยังค้างอยู่ในฐาน**
-- ⇒ แถวพวกนี้ยังติดป้าย "↳" (เป็นการตอบ) ทั้งที่ไม่ใช่ เพราะ `isReply` อ่านจากคอลัมน์นี้ตรง ๆ
-- ปิดทางเขียนใหม่อย่างเดียวไม่พอ ของเก่าต้องล้าง (docs/conventions/stored-flag-vs-owner-truth.md)
--
-- ## เกณฑ์ — ตัวเดียวกับโค้ดเป๊ะ (Hard Rule 16)
--
-- id ของ Meta อยู่ในรูป `{objectId}_{n}` และ **reply ต้องอยู่บน object เดียวกับตัวมันเอง**
-- ⇒ เป็น reply ก็ต่อเมื่อ objectId ตัวหน้าของ parent กับของตัวเองตรงกัน
-- (ตรงกับ `resolveCommentParentId()` ซึ่งมีเทส [blocker] 6 เคสยึดค่าจาก payload จริงกำกับอยู่)
--
-- ## ทำไมมี NOT EXISTS ทั้งที่วัดแล้วได้ 0
--
-- วัดบน prod ก่อนเขียน (2026-08-20): prefix ไม่ตรง **และ** หาแถวแม่ไม่เจอ = 8 แถว ·
-- prefix ไม่ตรง **แต่มีแม่จริง** = **0 แถว** · reply ปกติ 677 · reply ที่แม่ยังไม่ถูกเก็บ 6
-- เงื่อนไข NOT EXISTS จึงไม่เปลี่ยนผลลัพธ์วันนี้เลย — ใส่ไว้เป็น fail-safe: ถ้าข้อสันนิษฐานเรื่อง
-- รูปแบบ id ผิดในอนาคต คำสั่งนี้จะไม่ไปล้าง reply ที่มีแม่อยู่จริง (การเดาผิดทางนั้นทำให้คำตอบของ
-- ลูกค้าหลุดออกจากกิ่ง = ความเสียหายแบบเดียวกับบั๊กที่กำลังแก้อยู่ แค่กลับด้าน)
--
-- ## สิ่งที่จงใจ "ไม่" ทำ
--
-- 🛑 **ไม่แตะ 6 แถวที่ prefix ตรงกันแต่หาแม่ไม่เจอ** — พวกนั้นเป็น reply จริง เราแค่ไม่เคยเก็บ
-- คอมเมนต์แม่ไว้ (backfill ดึงหน้าเดียว 30 อันแล้วทิ้ง cursor) การตั้ง NULL ให้ด้วยคือการโกหกว่า
-- มันเป็นคอมเมนต์ระดับบน ทางแก้ของกลุ่มนั้นคือไปดึงแม่มาเก็บ ไม่ใช่ล้างค่า
-- 🛑 **ไม่แตะ `updatedAt`** — นี่คือการแก้ค่าที่เราบันทึกผิดเอง ไม่ใช่คอมเมนต์ถูกแก้ไข
-- (ตรวจแล้วว่าไม่มีโค้ดไหนอ่านคอลัมน์นี้ของตาราง PageComment อยู่)
--
-- idempotent: รันซ้ำได้ ครั้งที่สองจะไม่เข้าเงื่อนไขแล้วเพราะ parentExternalId เป็น NULL ไปแล้ว
UPDATE "PageComment" c
SET "parentExternalId" = NULL
WHERE c."parentExternalId" IS NOT NULL
  AND position('_' in c."externalCommentId") > 0
  AND position('_' in c."parentExternalId") > 0
  AND split_part(c."parentExternalId", '_', 1) <> split_part(c."externalCommentId", '_', 1)
  AND NOT EXISTS (
    SELECT 1 FROM "PageComment" p WHERE p."externalCommentId" = c."parentExternalId"
  );
