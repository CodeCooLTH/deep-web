-- feature 00059 (รายงานผลงานแอดมิน) — index รองรับการเลือก "เธรดที่เปิดในช่วงเวลานี้"
--
-- ทำไมต้องมี: รายงานนี้เริ่มจากคำถามเดียวคือ "เธรดของร้านนี้ที่ถูกเปิดใน [from, to) มีอะไรบ้าง"
-- แล้ว query ที่เหลือทั้งหมด JOIN ต่อจากชุดนั้น. `Conversation` มี index ของ `lastMessageAt`
-- และ `lastInboundAt` อยู่แล้ว แต่ **ไม่มีของ `createdAt` เลย** ⇒ ทุกคำขอต้องอ่านเธรดทั้งร้าน
-- แล้วค่อยทิ้งที่อยู่นอกช่วง ซึ่งโตตามอายุร้าน ไม่ใช่ตามช่วงที่ผู้ใช้ขอ
--
-- 🛑 ทำไมไม่ใช้ `lastMessageAt` ที่มี index อยู่แล้วแทน: มันคือ "ข้อความล่าสุด" ซึ่งขยับทุกครั้ง
-- ที่มีใครพิมพ์ — เธรดจากเดือนที่แล้วที่ลูกค้าเพิ่งทักวันนี้จะกระโดดเข้ามาอยู่ในช่วงของวันนี้
-- แล้วเวลาตอบครั้งแรกของมัน (ซึ่งเกิดเดือนที่แล้ว) จะถูกนับเป็นผลงานของสัปดาห์นี้
--
-- 🛑 คำสั่งเดียวในไฟล์นี้เป็น CREATE INDEX ล้วน — ไม่มี DROP/ALTER/DELETE
--    ไม่เปลี่ยนผลลัพธ์ของ query ใด ๆ ที่มีอยู่ เพิ่มความเร็วอย่างเดียว
--    (ขนาดตารางบน prod เล็ก — ChatMessage ทั้งฐาน ~40,700 แถว ณ 2026-08-20 — การสร้าง
--     index บน Conversation จึงใช้เวลาระดับมิลลิวินาที ไม่ต้อง CONCURRENTLY
--     ซึ่งใช้ไม่ได้อยู่แล้วเพราะ prisma migrate deploy ห่อทุกไฟล์ไว้ในทรานแซกชัน)
CREATE INDEX IF NOT EXISTS "Conversation_shopId_createdAt_idx"
  ON "Conversation" ("shopId", "createdAt");
