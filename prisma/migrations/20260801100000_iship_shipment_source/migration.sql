-- feature 00022 (ส่วนขยาย) — แยกใบที่ "ผูกเข้ามา" ออกจากใบที่ Deep เปิดเอง
--
-- ร้านที่เปิดพัสดุบนเว็บ iShip ไว้ก่อนแล้วค่อยมาบันทึกคำสั่งซื้อทีหลัง ต้องผูกใบเดิม
-- เข้ากับคำสั่งซื้อได้ ไม่ใช่ถูกบังคับให้เปิดใบที่สอง
--
-- ทำไมต้องมีคอลัมน์นี้ ไม่ใช่เดาจากข้อมูลอื่น:
--   1. ปุ่ม "ยกเลิก" คนละความหมาย — ใบที่เราเปิดเอง ยกเลิก = ยกเลิกพัสดุจริงกับขนส่ง
--      ส่วนใบที่ผูกเข้ามา ร้านมักตั้งใจแค่ "ตัดความสัมพันธ์" เพราะผูกผิดใบ
--   2. สถิติ "เปิดพัสดุผ่าน Deep" จะเฟ้อทันทีถ้านับรวมใบที่ร้านไปเปิดที่อื่นมาเอง
--   3. idempotencyKey ของสองชนิดคนละรูป (ใบที่ผูกไม่เคยมี custom_order_id ของเรา)
--      เดาจากรูปคีย์ได้ก็จริง แต่นั่นคือการฝังกฎไว้ในสตริง ซึ่งอ่านไม่ออกจากตาราง
--
-- DEFAULT 'CREATED' ทำให้แถวเดิมทั้งหมดแปลว่า "Deep เปิดเอง" ซึ่งตรงกับความจริง
-- เพราะก่อนหน้านี้ยังไม่มีทางผูกใบจากภายนอกเข้ามาได้เลย
ALTER TABLE "OrderShipment"
  ADD COLUMN "source" TEXT NOT NULL DEFAULT 'CREATED';

-- linkedAt: ผูกเมื่อไหร่ — ไม่ใช้ createdAt แทน เพราะ createdAt ของแถวนี้คือ "เวลาที่เรา
-- บันทึก" ส่วนพัสดุจริงอาจถูกเปิดไว้ตั้งแต่เมื่อวาน สองค่านี้ต่างกันโดยธรรมชาติ
ALTER TABLE "OrderShipment"
  ADD COLUMN "linkedAt" TIMESTAMP(3);

-- ค้นหน้ารายการ/สถิติด้วย source ระดับร้าน
CREATE INDEX "OrderShipment_shopId_source_idx" ON "OrderShipment"("shopId", "source");
