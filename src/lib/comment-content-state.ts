/**
 * comment-content-state — "คอมเมนต์ใบนี้มีเนื้อหาอะไรให้แสดง" (SSOT ตาม Hard Rule 16)
 *
 * ## ทำไมต้องแยก 3 สถานะ ไม่ใช่ 2
 *
 * เดิมทั้งแถวพรีวิวและบับเบิลเขียนเหมือนกันว่า `message || '(ไม่มีข้อความ)'` โดย **ไม่เคยดู
 * `attachmentUrl` เลย** ⇒ ยุบสองสถานะที่ต่างกันโดยสิ้นเชิงให้เหลือสตริงเดียว:
 *
 *   1. `TEXT`            — มีข้อความ แสดงตามปกติ
 *   2. `ATTACHMENT_ONLY` — ลูกค้าส่ง **รูป** ไม่มีแคปชัน (ข้อมูลมาครบ หน้าจอแค่ไม่ยอมอ่านฟิลด์)
 *   3. `UNAVAILABLE`     — **เราไม่รู้ว่าลูกค้าส่งอะไรมา** (Meta ไม่เคยส่งเนื้อหามาทาง webhook เลย
 *                          พิสูจน์จาก rawPayload จริงบน prod: payload ของคอมเมนต์สติกเกอร์มีแค่
 *                          from/verb/ids ไม่มี message/photo/video สักคีย์ — 18 แถวบน prod)
 *
 * 🛑 คำเดิม `(ไม่มีข้อความ)` **โกหกในสถานะ 3** — มันบอกว่า "ลูกค้าไม่ได้พิมพ์อะไร" ทั้งที่ความจริงคือ
 * "เราไม่มีข้อมูล" ผู้ขายที่อ่านแบบแรกจะข้ามคอมเมนต์นั้นไปเลย ทั้งที่อาจเป็นคนที่กำลังจะซื้อ
 * (user เจอเองบน prod 2026-08-20 พร้อมภาพจาก Facebook ที่ยืนยันว่าคอมเมนต์ใบนั้นมีรูปอยู่จริง)
 *
 * ## whitespace ล้วนนับเป็น "ไม่มีข้อความ"
 *
 * ต้อง `.trim()` เสมอ — ของเดิมพรีวิวใช้ `?.trim() ||` แต่บับเบิลใช้ `?? ` เฉย ๆ ⇒ คอมเมนต์ที่มีแต่
 * ช่องว่างจะแสดงต่างกันสองที่บนจอเดียวกัน (ช่องโหว่ที่มีอยู่ก่อนแล้ว ปิดไปพร้อมกันรอบนี้)
 *
 * ## ที่แสดงต่างกันได้ แม้สถานะเดียวกัน
 *
 * **แถวพรีวิว** ไม่มีรูปคอมเมนต์ให้ดูเลย (รูปบนแถวคือปกโพสต์) ⇒ สถานะ 2 ต้องมีคำ `[รูปภาพ]`
 * เป็นตัวแทน · **บับเบิลในเธรด** มีรูปจริงแสดงอยู่แล้วบรรทัดถัดไป ⇒ สถานะ 2 **ไม่ต้อง render
 * บรรทัดข้อความเลย** ให้รูปพูดแทน (precedent เขียนไว้ตรง ๆ ที่ `ChatThread.tsx`:
 * "รูปเปล่าไม่ต้องมีคำว่า '[รูปภาพ]' ซ้ำกับรูปที่เห็นอยู่")
 * — คำมาจาก SSOT เดียวกัน ต่างแค่ *ตำแหน่งที่ต้องแสดง* ตามว่าที่นั่นมีรูปให้ดูอยู่แล้วหรือไม่
 */

export type CommentContentState = 'TEXT' | 'ATTACHMENT_ONLY' | 'UNAVAILABLE'

export function commentContentState(comment: {
  message?: string | null
  attachmentUrl?: string | null
}): CommentContentState {
  if (comment.message?.trim()) return 'TEXT'
  return comment.attachmentUrl ? 'ATTACHMENT_ONLY' : 'UNAVAILABLE'
}
