/**
 * chat-attach-sheet — เงื่อนไขว่าชีตพรีวิวไฟล์แนบเต็มจอ (มือถือ) ควรแสดงไหม (2026-08-14)
 *
 * 🛑 อยู่ที่นี่ไม่ใช่ในเทอร์นารีกลาง JSX เพราะ boolean ที่ตัดสินว่า UI จะทำ/ไม่ทำอะไร ต้องมีที่ให้
 * เทสจับ — เขียนกลับด้านแล้วต้องมีอะไรแดง (docs/conventions/ui-boolean-needs-a-testable-home.md
 * — เคสจริง 2026-08-09: guard ปุ่ม "ย่อกลับ" เขียนกลับด้านแล้วผ่านทุก gate เพราะชนิดถูกทุกประการ)
 *
 * กติกาสำคัญที่สุดของฟังก์ชันนี้: **คิว `pendingImages` มีคนเขียน 3 ราย แต่มีรายเดียวที่แปลว่า
 * "ผู้ใช้กำลังจะส่งไฟล์"** — เลือก/วาง/ลากไฟล์เอง. อีกสองราย (ข้อความสำเร็จรูปที่มีรูป, เลือกสินค้า)
 * เติมคิวเป็นผลพลอยได้ของการเลือก *ข้อความ* และเนื้อหาถูกเติมลงช่องพิมพ์ ⇒ ชีตเต็มจอจะบังสิ่งที่
 * เพิ่งเติมไปพอดี. ห้าม derive จาก `pendingCount > 0` เด็ดขาด
 */

export type AttachSheetInput = {
  /** viewport < 768px (matchMedia ฝั่งผู้เรียก) */
  isMobileComposer: boolean
  /** ผู้ใช้เพิ่มไฟล์เองในรอบนี้ และยังไม่ได้กดปิด/กดส่ง */
  requestedOpen: boolean
  /** จำนวนไฟล์ที่อัปโหลดสำเร็จและรออยู่ในคิว */
  pendingCount: number
}

/**
 * ต้องครบทั้ง 3 เงื่อนไข:
 *  1. อยู่บนมือถือ — เดสก์ท็อป/แท็บเล็ตใช้แถบ thumbnail เดิม ไม่มีชีต
 *  2. ผู้ใช้เป็นคนสั่งเปิดเอง (เพิ่มไฟล์) — ไม่ใช่คิวที่ถูกเติมจากทางอื่น
 *  3. ยังมีไฟล์เหลืออยู่ — ลบจนหมดแล้วชีตต้องปิดเอง (ไม่งั้นเหลือจอเปล่ากับปุ่ม "ส่ง 0 รายการ")
 */
export function shouldShowAttachPreviewSheet({
  isMobileComposer,
  requestedOpen,
  pendingCount,
}: AttachSheetInput): boolean {
  return isMobileComposer && requestedOpen && pendingCount > 0
}
