/**
 * apple/native-nonce — ค่าคงที่ของ nonce ที่ผูกรอบล็อกอินด้วยแผ่นของระบบ
 * (feature 00040 · ภาคผนวก 7)
 *
 * 🛑 **แยกออกจากไฟล์ `route.ts` โดยตั้งใจ** — มี route 2 ตัวที่ต้องใช้ค่าเดียวกัน
 * (`/api/login/apple-native` และ `/api/account/link/apple-native`) ถ้าตัวหนึ่ง import
 * จากไฟล์ route ของอีกตัว มันจะลาก module ทั้งก้อน (รวม handler) เข้าไปด้วย
 * และ Next.js ถือว่า `route.ts` ควร export เฉพาะ HTTP method + config ที่รู้จัก
 * ⇒ ค่าคงที่ที่ใช้ร่วมกันต้องอยู่ใน `lib/` ไม่ใช่ในไฟล์ route
 *
 * ## ทำไม nonce ต้องมาจากเซิร์ฟเวอร์ ไม่ใช่ให้หน้าเว็บสุ่มเอง
 *
 * ร่างแรกของงานนี้ให้หน้าเว็บสุ่มแล้วส่งมาพร้อมโทเคน — **ซึ่งกันการเล่นโทเคนซ้ำไม่ได้เลย**
 * เพราะผู้โจมตีคุมทั้งสองฝั่งของการเทียบ: เขาส่งโทเคนที่ขโมยมา พร้อมกับค่า `nonce`
 * ที่อ่านออกมาจากโทเคนใบนั้นเอง แล้วด่านก็ผ่านทุกครั้ง
 * (คอมเมนต์ในร่างแรกอ้างว่ากันได้ — เป็นคำอ้างที่ผิด จับได้ตอนทบทวนก่อน merge
 * · คลาสเดียวกับ `docs/conventions/value-fate-decided-at-write-site.md`)
 *
 * เก็บใน **คุกกี้ httpOnly** ทำให้:
 *   - จาวาสคริปต์ในหน้าอ่านหรือแก้ไม่ได้ ⇒ ค่าที่ใช้เทียบไม่ได้มาจากฝั่งที่เชื่อไม่ได้
 *   - โทเคนเก่าที่ขโมยมาถือ nonce ของรอบอื่น ⇒ ไม่มีวันตรงกับคุกกี้ของรอบนี้
 *   - ใช้ได้ครั้งเดียว (ตัวตรวจลบคุกกี้ทิ้งทุกทางออก)
 */
import { NextResponse } from 'next/server'

/** ชื่อคุกกี้ที่ถือ nonce ของรอบนี้ — **ตัวตรวจทั้งสองตัวต้องอ่านชื่อเดียวกันนี้** */
export const APPLE_NONCE_COOKIE = 'deep_apple_nonce'

/**
 * 10 นาที — ยาวพอให้ผู้ใช้ผ่าน Face ID / รหัส Apple ID / 2FA ซึ่ง Apple เป็นเจ้าของเวลา
 * และสั้นพอที่คุกกี้ค้างจะหมดอายุก่อนจะมีใครเอาไปทำอะไรได้ (เท่าอายุของ identity token พอดี)
 */
export const APPLE_NONCE_MAX_AGE_SEC = 600

/**
 * ตอบพร้อม **ลบคุกกี้ nonce ทิ้งเสมอ** — ใช้ได้ครั้งเดียวจริง ๆ
 *
 * 🛑 ต้องลบทุกทางออก ไม่ใช่เฉพาะทางที่สำเร็จ: ถ้าลบเฉพาะตอนผ่าน คนที่ยิงโทเคนผิดจะยัง
 * มีคุกกี้เดิมให้ลองซ้ำได้เรื่อย ๆ ซึ่งคือสิ่งที่ "ใช้ครั้งเดียว" มีไว้กัน
 *
 * 🛑 อยู่ที่นี่ที่เดียว ไม่ให้แต่ละ route เขียนเอง — สอง route ที่ใช้ nonce นี้ต้องล้างเหมือนกัน
 * เป๊ะ ๆ และ "ลืมล้างในสาขาที่ไม่สำเร็จ" คือความผิดพลาดที่มองไม่เห็นจนกว่าจะมีคนไล่ยิง (HR16)
 */
export function replyClearingAppleNonce(body: unknown, status = 200): NextResponse {
  const res = NextResponse.json(body, { status })
  res.cookies.set(APPLE_NONCE_COOKIE, '', { path: '/', maxAge: 0 })
  return res
}
