/**
 * กฎ "แก้เบอร์บนออเดอร์ = แก้เบอร์ของลูกค้าคนเดิม หรือ ย้ายไปลูกค้าคนใหม่"
 *
 * ที่มา (user 2026-08-10): แอดมินแก้เบอร์ที่คีย์ผิดในโมดัลของห้องแชท แล้วมองว่า
 * "2 เบอร์นี้ต้องเป็นลูกค้าคนเดียวกัน" — ซึ่งถูกในมุมธุรกิจ แต่โมเดลข้อมูลเก็บแบบนั้นไม่ได้:
 * `Customer.phone` เป็น unique **ทั้งระบบ** และ `Customer` เป็นตัวตน **ข้ามร้าน**
 * (`findOrCreateCustomer` เขียนกำกับไว้เอง) ⇒ 1 เบอร์ = 1 แถว = 1 ตัวตน เสมอ
 *
 * ทางออกที่ user เคาะ: ถ้า**พิสูจน์ได้**ว่าแถวเดิมเป็นเศษที่เกิดจากการคีย์ผิด (ไม่มีใครเป็นเจ้าของจริง)
 * ให้ **แก้เบอร์ในแถวเดิม** — ลูกค้ายังเป็นคนเดิม id เดิม ประวัติทั้งหมดติดตามไปด้วยโดยไม่ต้องย้ายอะไร
 * พิสูจน์ไม่ได้เมื่อไหร่ห้ามแตะ เพราะการเปลี่ยนเบอร์ของแถวที่มีเจ้าของจริง = เปลี่ยนตัวตนของคนอื่น
 * ในร้านอื่นไปด้วยพร้อมกัน โดยที่ไม่มีใครในร้านนั้นรู้เรื่อง
 *
 * 🛑 ทุกเงื่อนไขเป็น "ห้ามเมื่อ" ไม่ใช่ "อนุญาตเมื่อ" — ค่าที่นับไม่ได้/ยังไม่รู้ ต้องแปลว่าไม่ปลอดภัย
 * (fail-closed) เพราะผลของการเดาผิดคือข้อมูลตัวตนของลูกค้าคนอื่นถูกเขียนทับแบบกู้คืนไม่ได้
 */

export interface CustomerPhoneRenameInput {
  /** แถวเดิมถูกอัปเกรดเป็นบัญชีผู้ซื้อจริงแล้ว (`Customer.userId` ไม่ null) — เบอร์คือตัวตนที่เขายืนยันเอง */
  hasLinkedUserAccount: boolean
  /** ออเดอร์ใบอื่นที่ผูกกับแถวเดิม **ทุกร้านในระบบ** (ไม่นับใบที่กำลังแก้อยู่) */
  otherOrderCount: number
  /** เธรดแชทอื่นที่ผูกกับแถวเดิม (ไม่นับเธรดที่กำลังทำงานอยู่) */
  otherContactCount: number
  /** เบอร์ใหม่มี Customer เจ้าของอยู่แล้ว → rename ไม่ได้ (unique) และต้องไปรวมกับแถวนั้นแทน */
  newPhoneTaken: boolean
}

export function canRenameCustomerPhone(input: CustomerPhoneRenameInput): boolean {
  if (input.hasLinkedUserAccount) return false
  if (input.otherOrderCount > 0) return false
  if (input.otherContactCount > 0) return false
  if (input.newPhoneTaken) return false
  return true
}
