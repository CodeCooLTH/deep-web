/**
 * 00061 — ตัวแปลงข้อความของ "สร้างออเดอร์อัตโนมัติจากคำสั่งในแชท" (SRS TFR-002, TFR-015)
 *
 * 🛑 ห้าม reuse `normalizeMessage()` จาก `auto-reply-normalize.ts` เด็ดขาด
 * ไฟล์นั้นมี 8 ขั้น และ **ขั้น 6 แทน `/` ด้วยช่องว่าง** ⇒ วลี `/go` จะกลายเป็น `go`
 * ซึ่งชนกับคำว่า "go" เปล่า ๆ ที่ร้านอาจพิมพ์ในประโยคปกติ — วลีจุดชนวนต้องเก็บสัญลักษณ์ไว้ครบ
 *
 * ไฟล์นี้ไม่ import อะไรนอกจาก `node:crypto` โดยตั้งใจ (pure + เทสได้โดยไม่แตะ DB)
 */
import { createHash } from "node:crypto";

/**
 * normalizeTriggerPhrase — ใช้ทั้งตอนบันทึกวลีลง `AutoOrderAgentPhrase.normalizedPhrase`
 * และตอนเทียบข้อความที่ร้านพิมพ์ **ต้องเป็นตัวเดียวกันทั้งสองฝั่งเสมอ**
 *
 * ทำ 3 ขั้นเท่านั้น — 🛑 **ไม่มีขั้นลบสัญลักษณ์/วรรคตอนใด ๆ**
 *   1. Unicode NFC — ให้อักขระที่ "หน้าตาเหมือนกัน" มีรูป code point เดียวกันก่อนเทียบ
 *   2. lowercase (มีผลกับอังกฤษเท่านั้น — ไทยไม่มี case)
 *   3. ยุบช่องว่างทุกชนิดเป็น " " ตัวเดียว แล้วตัดหัวท้าย
 *
 * 📝 ขั้น NFC ไม่ได้อยู่ใน SRS TFR-002 ฉบับแรก (เขียนไว้ว่า "แค่ 2 ขั้น") — เพิ่มตอน implement
 * เพราะ **มันไม่ลบอะไรทิ้ง** แต่กันเคสที่วลีเดียวกันพิมพ์จากคนละอุปกรณ์แล้วไม่ match โดยไม่มีอะไรฟ้อง
 * (ไทยมีสระ/วรรณยุกต์เป็น combining mark — ลำดับต่างกันได้จริง) · SRS ถูกอัปเดตให้ตรงแล้ว
 */
export function normalizeTriggerPhrase(input: string): string {
  return input
    .normalize("NFC")
    .toLowerCase()
    .replace(/[\s ​　﻿]+/g, " ")
    .trim();
}

/**
 * computeContentHash — คีย์กันข้อความซ้ำในห้องเดียวกันภายใน 2 นาที (TFR-015)
 *
 * 🛑 ห้ามส่ง `normalizeTriggerPhrase(x)` เข้ามา — พารามิเตอร์ชื่อ `rawBody` เพราะต้องเป็น
 * **ข้อความดิบเสมอ** BR-ACO-20a บังคับว่า "ต่างแม้ตัวอักษรเดียว = ใบใหม่" ⇒ ถ้าฮาชจากข้อความ
 * ที่ผ่าน normalize มาแล้ว ช่องว่างซ้ำที่ถูกยุบทิ้งจะทำให้ 2 ข้อความที่ต่างกันจริงได้ hash เดียวกัน
 *
 * 🛑 เวลาไม่ใช่ส่วนหนึ่งของ hash โดยตั้งใจ — ถ้ารวม timestamp เข้าไป ทุกข้อความจะได้ hash ไม่ซ้ำเสมอ
 * แล้ว **กลไกกันซ้ำทั้งตัวจะกลายเป็น no-op ทันที** · เวลาเป็นเงื่อนไขของ query (`createdAt > now-2min`)
 * ไม่ใช่ส่วนหนึ่งของคีย์ — hash ตอบว่า "เนื้อหาเดียวกันไหม" เวลาตอบว่า "อยู่ในหน้าต่างที่ยอมให้ซ้ำไหม"
 */
export function computeContentHash(rawBody: string): string {
  return createHash("sha256").update(rawBody, "utf8").digest("hex");
}
