import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { describe, expect, it } from 'vitest'

/**
 * [blocker] บล็อกร้าน + โซนรีวิว บนหน้าออเดอร์ผู้ซื้อ `/o/[token]`
 *
 * ทั้งสองอย่างในไฟล์นี้ปิด **ช่องว่างที่ผู้ซื้อมองไม่เห็นว่ามีอยู่**:
 *
 * 1. ชื่อร้านเป็นลิงก์มาตลอด แต่ไม่มีอะไรบอกว่ากดได้ (ไม่มีขีดเส้นใต้ ไม่มีสี ใช้ `text.primary`)
 *    ⇒ คนที่อยากเช็คความน่าเชื่อถือของร้านก่อนโอนเงิน ไม่มีทางเข้าที่มองเห็นเลย
 *    **บนหน้าที่สร้างมาเพื่อความน่าเชื่อถือ**
 *
 * 2. ออเดอร์ที่ยัง `PENDING` ไม่มี UI เรื่องรีวิวเลยสักชิ้น ⇒ ผู้ซื้อไม่รู้ว่าระบบมีรีวิว
 *    ไม่รู้ว่าจะเปิดเมื่อไร และไม่รู้ว่าต้องทำอะไรถึงจะได้เขียน — ทั้งที่รีวิวคือสิ่งที่ทำให้
 *    ร้านถัดไปน่าเชื่อถือ ซึ่งเป็นเหตุผลที่ระบบนี้มีอยู่
 *
 * 🛑 แดง = ห้าม merge
 */
const REL = 'src/app/(marketing)/o/[token]/OrderDetailMobile.tsx'

/** ตัดคอมเมนต์ทิ้งก่อนสแกน — ไฟล์นี้อธิบายกฎของตัวเองไว้ยาว สแกนดิบจะเจอคอมเมนต์ */
const code = (() => {
  const raw = readFileSync(join(process.cwd(), REL), 'utf8')
  return raw
    .replace(/\{\/\*[\s\S]*?\*\/\}|\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/(?<!:)\/\/.*$/gm, (m) => ' '.repeat(m.length))
})()

describe('[blocker] บล็อกร้าน', () => {
  it('ต้องมีทางเข้าโปรไฟล์ร้านที่มองเห็น ไม่ใช่แค่ชื่อร้านที่กดได้', () => {
    const at = code.indexOf('ดูโปรไฟล์ร้าน')
    expect(at, 'ต้องมีปุ่มไปโปรไฟล์ร้าน').toBeGreaterThan(-1)

    /* ต้องเป็นปุ่มจริงและชี้ไปโปรไฟล์ร้านจริง — ข้อความเปล่า ๆ ที่กดไม่ได้ไม่นับ

       🛑 **ห้ามใช้หน้าต่างความยาวคงที่** — ไฟล์นี้แทนคอมเมนต์ด้วยช่องว่างที่ยาวเท่าเดิม
       การเพิ่มคำอธิบายเหนือปุ่มจึงดัน `<Button` หลุดกรอบ แล้วแดงทั้งที่ของถูก
       (พลาดแบบเดียวกันเป็นครั้งที่หกในงานนี้ — เลิกใช้ระยะ ใช้ "ตัวเปิดที่ใกล้ที่สุด" แทน) */
    const btn = code.lastIndexOf('<Button', at)
    expect(btn, 'ต้องเป็น Button').toBeGreaterThan(-1)
    const block = code.slice(btn, at)
    expect(block, 'ต้องชี้ /u/{username}').toMatch(/href=\{`\/u\/\$\{order\.shop\.user\.username\}`\}/)
  })

  it('ปุ่มโปรไฟล์ร้านต้องไม่แย่งน้ำหนักกับปุ่มที่เดินเรื่องออเดอร์', () => {
    /* ปุ่มทึบ (`contained`) บนหน้านี้สงวนไว้ให้ปุ่มที่เดินเรื่อง (ยืนยัน/แนบสลิป) —
       การไปดูโปรไฟล์เป็นการ *หาข้อมูลเพิ่ม* ไม่ใช่ขั้นตอนของงาน
       ถ้าทำเป็นปุ่มทึบ จะแข่งสายตากับปุ่มที่กดแล้วปิดงานถาวร ซึ่งอันตราย */
    const at = code.indexOf('ดูโปรไฟล์ร้าน')
    const btn = code.lastIndexOf('<Button', at)
    expect(btn).toBeGreaterThan(-1)
    expect(code.slice(btn, at), 'ห้ามเป็นปุ่มทึบ').not.toMatch(/variant='contained'/)
  })
})

describe('[blocker] โซนรีวิว', () => {
  it('ออเดอร์ที่ยังเขียนรีวิวไม่ได้ ต้องบอกว่าจะเปิดเมื่อไร', () => {
    const at = code.indexOf('เขียนรีวิวได้หลังกด')
    expect(at, 'ต้องมีการ์ดรีวิวแบบยังไม่เปิด').toBeGreaterThan(-1)
  })

  it('การ์ดรีวิวที่ยังไม่เปิด ต้องไม่ขึ้นกับใบที่ยกเลิกแล้ว', () => {
    /* 🛑 ใบที่ยกเลิกจะไม่มีวันได้รีวิว — ขึ้นการ์ดนี้คือสัญญาสิ่งที่จะไม่เกิดขึ้น
       (คลาสเดียวกับ note บนรางที่ต้องถูกทิ้งเมื่อใบถูกยกเลิก) */
    const guard = code.search(/!order\.hasReview\s*&&\s*!canReview\s*&&\s*!isCancelled/)
    expect(guard, 'ต้องมีตัวกั้นครบทั้ง 3 เงื่อนไข').toBeGreaterThan(-1)
    expect(code.indexOf('เขียนรีวิวได้หลังกด'), 'ข้อความต้องอยู่หลังตัวกั้น').toBeGreaterThan(guard)
  })

  it('ต้องอ้างคำบนปุ่มจริง ไม่พิมพ์คำซ้ำเอง', () => {
    /* 🛑 พิมพ์ "ยืนยันว่ารับบริการแล้ว" ซ้ำที่นี่ = วันที่คำบนปุ่มเปลี่ยน การ์ดจะบอกให้กดปุ่ม
       ที่ไม่มีอยู่ โดยไม่มี tsc/เทสตัวไหนฟ้อง (HR16 — เหตุผลเดียวกับกล่องอธิบายบนราง) */
    const at = code.indexOf('เขียนรีวิวได้หลังกด')
    expect(code.slice(at, at + 200), 'ต้องแทรก {ctaLabel}').toMatch(/\{ctaLabel\}/)
  })

  it('ดาวที่ยังกดไม่ได้ ต้องเป็นสีจางและถูกข้ามโดย screen reader', () => {
    /* สีเหลืองอ่านเป็น "มีคะแนนแล้ว" ซึ่งไม่จริง · และดาว 5 ดวงที่ไม่ได้สื่อคะแนนอะไร
       ถ้าถูกอ่านออกมาจะกลายเป็นข้อมูลปลอม (ข้อความใต้ดาวบอกครบอยู่แล้ว) */
    /* 🛑 ต้องตัดมาเฉพาะ **การ์ดที่ยังไม่เปิด** — `tabler-star-filled` มีอยู่ในการ์ดรีวิวจริง
       (ที่แสดงคะแนนที่ลูกค้าให้ไว้) ด้วย และอยู่ก่อนหน้าในไฟล์ ⇒ `indexOf` เปล่า ๆ ไปเจอตัวนั้น
       แล้วเทสจะตรวจดาวผิดใบทั้งที่ชื่อเทสบอกว่าตรวจดาวจาง
       (`mutation-silence-means-weak-corpus.md` — first-occurrence เจอเป็นครั้งที่สามในงานนี้) */
    const guard = code.search(/!order\.hasReview\s*&&\s*!canReview\s*&&\s*!isCancelled/)
    const msg = code.indexOf('เขียนรีวิวได้หลังกด')
    expect(guard, 'ต้องมีตัวกั้น').toBeGreaterThan(-1)
    const card = code.slice(guard, msg)
    expect(card, 'ต้องมีดาวในการ์ดที่ยังไม่เปิด').toMatch(/tabler-star-filled/)
    expect(card, 'ต้องเป็นสีจาง').toMatch(/action-disabled|text-disabled/)
    expect(card, 'ต้องมี aria-hidden').toMatch(/aria-hidden='true'/)
  })
})
