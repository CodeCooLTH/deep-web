import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { describe, expect, it } from 'vitest'

/**
 * [blocker] หัวหน้าจอ + รางสถานะของหน้าออเดอร์ลูกค้า `/o/[token]`
 *
 * ## กล่องอธิบายสอง "ยืนยัน" คือตัวกันความเสียหาย ไม่ใช่ของประดับ
 *
 * ราง 4 ขั้นของร้านบริการมีการ "ยืนยัน" ของลูกค้า **2 ขั้น** ที่คนละเรื่องกันสิ้นเชิง:
 *   ขั้น 2 "ลูกค้ายืนยันนัด"  = จะมาตามนัด · **ย้อนได้**
 *   ขั้น 4 "ยืนยันเสร็จสิ้น"   = ปิดงาน   · **ย้อนไม่ได้ + คะแนนร้านขยับ**
 *
 * ลูกค้าที่กดขั้น 4 ตั้งแต่ยังไม่ได้รับบริการจะเสียทางออกทั้งหมดในหนึ่งแตะ — ปุ่มแจ้งปัญหา
 * หายไปพร้อมกัน (เงื่อนไข `status !== 'CONFIRMED'`) นี่คือช่องทางสแกมแบบเดียวกับที่
 * `ctaLabel` ในไฟล์เดียวกันเขียนอธิบายไว้ยาว ๆ แค่ย้ายมาเกิดอีกขั้นหนึ่ง
 *
 * 🛑 เทสนี้เช็ค **พฤติกรรม** ไม่ใช่ถ้อยคำ — ถ้อยคำเปลี่ยนได้ แต่ 3 อย่างนี้ห้ามหาย:
 * กล่องต้องมีอยู่ · ต้องผูกกับเงื่อนไข "ยังกดผิดได้" · ต้องอ้างคำบนปุ่มจริงไม่ใช่พิมพ์ซ้ำ
 */
const ROOT = process.cwd()
const REL = 'src/app/(marketing)/o/[token]/OrderDetailMobile.tsx'

/** ลบเนื้อคอมเมนต์แต่คงจำนวนบรรทัด — ไฟล์นี้อธิบายกฎของตัวเองไว้ยาว สแกนดิบจะเจอคอมเมนต์ */
const code = (() => {
  const raw = readFileSync(join(ROOT, REL), 'utf8')
  return raw
    .replace(/\{\/\*[\s\S]*?\*\/\}|\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/(?<!:)\/\/.*$/gm, (m) => ' '.repeat(m.length))
})()

describe('[blocker] หน้าออเดอร์ลูกค้า — หัวเรื่อง + รางสถานะ', () => {
  it('กล่องอธิบายสอง "ยืนยัน" ต้องยังอยู่ และผูกกับเงื่อนไขที่ยังกดผิดได้', () => {
    expect(code, 'ต้องมีคำอธิบายว่า "ยืนยันนัดหมาย" คืออะไร').toMatch(/ยืนยันนัดหมาย/)
    expect(code, 'ต้องบอกว่าอีกอันย้อนกลับไม่ได้').toMatch(/ย้อนกลับไม่ได้/)

    /* ต้องอยู่หลัง `canConfirm` — ใบที่จบ/ยกเลิกแล้วอ่านแล้วสับสนเปล่า ๆ และที่สำคัญกว่าคือ
       กล่องนี้มีไว้เตือน "ก่อนกด" ใบที่กดไปแล้วไม่มีอะไรให้เตือน

       🛑 ยึด "ตัวกั้นอยู่ก่อนข้อความ" ไม่ใช่ "ข้อความอยู่ในหน้าต่าง N ตัวอักษรหลังตัวกั้น" —
       ระยะห่างเปลี่ยนได้ทุกครั้งที่ใครเพิ่ม prop ให้ `<Box>` แล้วเทสจะแดงทั้งที่ของยังถูก
       (ร่างแรกของเทสนี้ใช้หน้าต่าง 700 ตัวอักษร แล้วแดงทันทีเพราะ sx ยาวกว่านั้น) */
    const at = code.indexOf('ยืนยันนัดหมาย')
    const guard = code.search(/isServiceShop\s*&&\s*canConfirm\s*&&/)
    expect(guard, 'ต้องมีตัวกั้น isServiceShop && canConfirm').toBeGreaterThan(-1)
    expect(at, 'ข้อความอธิบายต้องอยู่หลังตัวกั้น').toBeGreaterThan(guard)

    /* และตัวกั้นต้องเป็นของ *กล่องนี้* ไม่ใช่ของบล็อกอื่นที่บังเอิญอยู่ก่อนหน้า —
       ระหว่างตัวกั้นกับข้อความต้องไม่มีตัวปิด JSX ของบล็อกอื่นคั่น */
    expect(code.slice(guard, at), 'ห้ามมีบล็อกอื่นคั่นระหว่างตัวกั้นกับข้อความ').not.toMatch(/\)\}/)
  })

  it('กล่องต้องอ้างคำบนปุ่มจริง (`ctaLabel`) ห้ามพิมพ์คำซ้ำเอง', () => {
    /* 🛑 พิมพ์ "ยืนยันว่ารับบริการแล้ว" ซ้ำที่นี่ = วันที่คำบนปุ่มเปลี่ยน กล่องจะอธิบายปุ่ม
       ที่ไม่มีอยู่แล้ว โดยไม่มี tsc/เทสตัวไหนฟ้อง (Hard Rule 16 ตรงตัว) */
    const at = code.indexOf('คือปิดงานหลังได้รับบริการจริง')
    expect(at, 'ต้องมีประโยคอธิบายขั้นปิดงาน').toBeGreaterThan(-1)
    const around = code.slice(Math.max(0, at - 400), at)
    expect(around, 'ต้องแทรก {ctaLabel} ไม่ใช่สตริงตายตัว').toMatch(/\{ctaLabel\}/)
  })

  it('เลขขั้นบนราง ต้องขึ้นเฉพาะร้านบริการ', () => {
    /* ราง 3 ขั้นของร้านขายของไม่เคยมีเลข — ใส่เพิ่มคือเปลี่ยนหน้าตาของ vertical
       ที่ไม่ได้อยู่ในขอบเขตงานนี้ (หน้าเดียวเสิร์ฟทั้ง ONLINE_SALES และ SERVICE_QUEUE) */
    expect(code).toMatch(/numbered=\{order\.isServiceShop\}/)
  })

  it('เลขคำสั่งซื้อต้องเป็นหัวเรื่อง (h1) และคัดลอกได้', () => {
    /* เลขนี้คือสิ่งที่ลูกค้าต้องอ่านให้ร้านฟังทางโทรศัพท์ — เดิมเป็นข้อความที่เล็กที่สุดในหน้า
       ชิดขวาแถวเดียวกับป้ายสถานะ และคัดลอกไม่ได้เลย */
    expect(code).toMatch(/component='h1'/)
    expect(code).toMatch(/handleCopyOrderNo/)
    expect(code, 'ปุ่มคัดลอกต้องมีชื่อให้ screen reader อ่าน (ปุ่มไอคอนล้วน)').toMatch(
      /aria-label='คัดลอกเลขคำสั่งซื้อ'/,
    )
  })

  it('[blocker] ธงคัดลอกเลขงานต้องแยกจากธงคัดลอกเลขพัสดุ', () => {
    /* 🛑 ใช้ตัวเดียวกันแล้วกดคัดลอกเลขงาน เช็กถูกจะไปโผล่ที่ปุ่มคัดลอกเลขพัสดุด้วย —
       สองปุ่มนี้อยู่บนจอเดียวกันได้พร้อมกันและเป็นคนละก้อนคนละความหมาย */
    expect(code).toMatch(/const \[copiedOrderNo, setCopiedOrderNo\]/)
    expect(code).toMatch(/const \[copied, setCopied\]/)
  })

  it('[blocker] รางต้องได้ hasAppointment จาก "มีนัดไหม" ไม่ใช่ "มีเวลาไหม"', () => {
    /* งาน walk-in ที่ร้านกด "เริ่มงานเลย" ก็ได้เวลา ทั้งที่ไม่เคยมีการนัดหมาย —
       เดาจากเวลา = ขั้น "ลูกค้ายืนยันนัด" ไปค้างรอในใบที่ไม่มีนัดให้ยืนยัน

       🛑 ต้องตัดมาเฉพาะบล็อกของ `getServiceTimeline` — ในไฟล์นี้มี `hasAppointment` **2 จุด**
       (ราง + ป้ายสถานะจาก `resolveServiceOrderBadge`) ร่างแรกของเทสค้นทั้งไฟล์ ⇒ mutation
       ที่เปลี่ยนจุดของรางไปเดาจากเวลา **ยังเขียว** เพราะไปเจออีกจุดที่ไม่ได้ถูกแตะ
       (`mutation-silence-means-weak-corpus.md` ตรงตัว) */
    const at = code.indexOf('getServiceTimeline({')
    expect(at, 'ต้องเรียก getServiceTimeline').toBeGreaterThan(-1)
    const block = code.slice(at, code.indexOf('})', at))
    expect(block, 'ในบล็อกของรางต้องเป็น order.appointment !== null').toMatch(
      /hasAppointment:\s*order\.appointment\s*!==\s*null/,
    )
    expect(block, 'ห้ามเดาจากเวลานัด').not.toMatch(/hasAppointment:[^\n]*startIso/)
  })
})
