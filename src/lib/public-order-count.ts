import type { Prisma } from "@prisma/client";
import { ACTIVE_FORWARD_SHIPMENT } from '@/lib/shipment-direction'

/**
 * SSOT ของ "ออเดอร์ใบไหนนับเป็นผลงานของร้านบนหน้าสาธารณะได้"
 * กฎเต็ม + เหตุผล: `docs/10 - Business Rules/Public Order Count.md` (BR-POC-01..04)
 *
 * หลักที่ใช้ตัดสิน: **นับได้เมื่อมีหลักฐานที่ร้านสร้างขึ้นเองไม่ได้** ไม่ใช่ "ออเดอร์เดินไปไกลแค่ไหน"
 *   - `Order.status = CONFIRMED` → ผู้ซื้อกดยืนยันเอง (ปลดล็อกด้วยเบอร์ตัวเอง) ปลอมไม่ได้
 *   - `carrierStatus` ที่ขยับจริง  → ขนส่งเป็นคนอัปเดต ปลอมไม่ได้
 *
 * 🛑 ห้ามใช้ `Order.status = SHIPPED` หรือ `OrderShipment.status = CREATED` เป็นเกณฑ์เด็ดขาด
 * ทั้งคู่เป็น**การกระทำของร้านเอง** (SHIPPED ตั้งที่ order.service.ts เมื่อร้านกดแจ้งส่ง ·
 * CREATED คือร้านกดสร้างใบปะหน้า) ร้านจึงปั่นตัวเลขได้ทั้งสองทาง ซึ่งคือช่องโหว่ที่กฎนี้มีไว้ปิด
 */

/**
 * สถานะขนส่งที่ถือว่า "ของออกจากร้านไปจริงแล้ว" — เกณฑ์ "กลาง" (user เคาะ 2026-08-10)
 *
 * 🛑 **ไม่มี `picked_up`** ทั้งที่ระบบจัดมันอยู่ในกลุ่ม in-transit — ป้ายไทยของมันคือ
 * "พัสดุเข้าระบบ" และมีบันทึกว่าขนส่งบางเจ้า (SPX) ยิงสถานะนี้ตั้งแต่ตอน**สร้าง**พัสดุ
 * ไม่ใช่ตอนรับของจริง ถ้านับเข้าไปด้วย ร้านที่ใช้เจ้านั้นจะได้แต้มฟรีทันทีที่กดสร้าง
 * = กลับไปสู่ช่องโหว่เดิมที่กฎนี้ตั้งใจปิด
 *
 * terminal ทั้งหมดนับด้วย (ส่งถึง/เก็บเงินสำเร็จ/ตีกลับถึงร้าน) — "ตีกลับ" ก็แปลว่าการซื้อขาย
 * เกิดขึ้นจริงและของเดินทางจริง แค่จบไม่สวย ซึ่งเป็นคนละคำถามกับ "สำเร็จไหม" (ดู BR-POC-04)
 */
export const COUNTABLE_CARRIER_STATUSES = [
  // ขยับจริงระหว่างทาง
  "with_branch",
  "in_transit",
  "progress",
  // จบเส้นทางแล้ว (ยกมาจากตาราง terminal ใน lib/iship/status.ts)
  "delivered",
  "payment_success",
  "return_success",
] as const;

/**
 * เงื่อนไข Prisma ของ "ออเดอร์ที่นับได้" — ใช้ตัวนี้ตัวเดียวทุกที่ (BR-POC-03)
 *
 * ตัวเลข 4 ตัวบนหน้าร้าน (ออเดอร์ · จำนวนลูกค้า · ลูกค้าซื้อซ้ำ · "ขายแล้ว N" รายสินค้า)
 * ต้องมาจากฟังก์ชันนี้ทั้งหมด ห้ามเขียนเงื่อนไขซ้ำ ไม่งั้นหน้าเดียวกันจะมีตัวเลขสองนิยาม
 * ซึ่งเป็นสิ่งที่ Hard Rule 16 ห้ามไว้ตรง ๆ
 *
 * 🛑 `completionRate` **ไม่ใช้** ฟังก์ชันนี้ — "สำเร็จ" แปลว่าผู้ซื้อได้ของแล้ว พัสดุที่ยังเดินทาง
 * อยู่ยังไม่ใช่ความสำเร็จ (BR-POC-04) อย่าเผลอเอาไปใช้กับสูตรอัตราสำเร็จเพราะเห็นว่าอยู่ไฟล์เดียวกัน
 */
export function countableOrderWhere(shopId: string): Prisma.OrderWhereInput {
  return {
    shopId,
    // ยกเลิกแล้วไม่นับ ไม่ว่าพัสดุจะเดินไปถึงไหน
    status: { not: "CANCELLED" },
    OR: [
      { status: "CONFIRMED" },
      {
        shipments: {
          some: {
            // นิยาม "พัสดุที่มีอยู่จริง" ตัวเดียวกับที่ระบบใช้ — ห้ามใช้ status <> 'CANCELLED'
            // ซึ่งนับใบ FAILED ด้วย (บั๊กที่เคยทำให้แถวขึ้นชิป "สร้างพัสดุแล้ว" ทั้งที่ไม่มีเลขพัสดุ)
            // + direction FORWARD (feature 00056): พัสดุขากลับของใบคืนต้องไม่ทำให้ตัวเลข
            // ออเดอร์บนโปรไฟล์สาธารณะเพิ่มขึ้น ซึ่งเป็นปัญหาเดิมที่ฟีเจอร์นี้ตั้งใจแก้
            ...ACTIVE_FORWARD_SHIPMENT,
            carrierStatus: { in: [...COUNTABLE_CARRIER_STATUSES] },
          },
        },
      },
    ],
  };
}
