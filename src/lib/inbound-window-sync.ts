/**
 * "ต้องถาม Meta หาเวลาที่ลูกค้าทักล่าสุดไหม" — ตัวตัดสินเดียวของหน้าเธรด
 *
 * 🛑 แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพราะมันคือเงื่อนไขที่ **แพงที่สุดในการเปิดห้องแชท**:
 * Graph call ตัวนี้วัดบน prod ได้ **median 680ms** (5 รอบ: 608/624/680/764/935) และมัน
 * บล็อกการวาดหน้า — ถ้าใครขยายเงื่อนไขกลับไปให้กว้างเหมือนเดิมโดยไม่ตั้งใจ จะไม่มีอะไรฟ้อง
 * นอกจากผู้ใช้บ่นว่าช้า (ซึ่งเกิดขึ้นมาแล้วจริง ๆ 2026-09-10)
 *
 * เกณฑ์: ถามเฉพาะตอน **เราไม่มีข้อมูลเลย** (`null`) ไม่ใช่ตอน "หน้าต่างดูปิด"
 *   · `null` = ร้านเชื่อมเพจช้ากว่าที่ลูกค้าทัก ⇒ ไม่เคยได้ webhook ⇒ ต้องถาม (487 เธรด · 5.2%)
 *   · มีค่าแล้วแต่เก่า = ลูกค้าเงียบไปจริง ค่าจาก webhook ถูกอยู่แล้ว (8,483 เธรด · 90.9%)
 *     ⇒ ถามซ้ำได้คำตอบเดิมเสมอ = จ่าย 680ms ฟรี
 *
 * DEEP ไม่มีแนวคิดนี้ · LINE ใช้ reply token 60 วินาที ไม่ใช่หน้าต่าง 24 ชม. ของ Meta
 * (เคยยิง Graph ของ Meta ด้วย token ของ LINE อยู่พักหนึ่ง — ล้มเงียบ เหลือแต่ latency)
 */
export function shouldAskMetaForInboundWindow(params: {
  channel: string
  lastInboundAt: Date | null
}): boolean {
  const { channel, lastInboundAt } = params
  if (channel === 'DEEP' || channel === 'LINE') return false
  return lastInboundAt === null
}
