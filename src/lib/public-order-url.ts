/** โดเมนฝั่งผู้ซื้อ — `NEXT_PUBLIC_*` จึงอ่านได้ทั้ง server และ client (inline ตอน build) */
export function publicBuyerBaseUrl(): string {
  return (process.env.NEXT_PUBLIC_BUYER_URL || "https://deepthailand.app").replace(/\/+$/, "");
}

/** ลิงก์หน้าออเดอร์สาธารณะของ token นี้ */
export function publicOrderUrl(publicToken: string): string {
  return `${publicBuyerBaseUrl()}/o/${publicToken}`;
}
