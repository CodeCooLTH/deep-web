/**
 * รูปร่างของ "รหัสภายใน" — ตัวพิมพ์ใหญ่ล้วน คั่นด้วย `_` ไม่มีช่องว่าง (`CHANNEL_NOT_ACTIVE`)
 *
 * 🛑 นี่คือ **ตาข่าย ไม่ใช่ทางหลัก** — ทางหลักคือมีกฎใน `RULES` ให้ครบทุกรหัสที่โผล่ถึงผู้ขายได้
 * ตาข่ายนี้มีไว้เพราะวันหน้าจะมีรหัสใหม่ที่คนเพิ่มลืมมาเติมกฎที่นี่ (เกิดมาแล้วกับ CR คิว 2026-08-23:
 * รหัสถูกย้ายจากเส้นทางที่ route แปลให้ ไปเป็นค่าที่เก็บลง DB โดยไม่มีใครสังเกต) — สิ่งที่มันรับประกัน
 * คือ "ผู้ขายไม่มีวันเห็นรหัสอังกฤษดิบบนหน้าจอ" ไม่ใช่ "ข้อความจะมีประโยชน์"
 *
 * ข้อความดิบจาก Meta/LINE ไม่เข้าเงื่อนไขนี้ (เป็นประโยคอังกฤษมีช่องว่าง/ตัวพิมพ์เล็ก) และข้อความ
 * ไทยที่ระบบเราสร้างเองก็ไม่เข้า — ตาข่ายจึงไม่กลืนอะไรที่อ่านออกอยู่แล้ว
 *
 * 🛑 **ห้ามบังคับว่าต้องมี `_`** (F-1 รอบแก้ 2 — รูปเดิม `^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$` พลาดตรงนี้):
 * รหัสภายในจำนวนมากเป็น **คำเดียว** ไม่มีขีดล่างเลย — `FORBIDDEN` (ซึ่งถึงหน้าจอได้จริง ดูกฎด้านบน) ·
 * `TIMEOUT` · `ECONNRESET` ⇒ หลุดออกดิบทั้งหมด. เกณฑ์ที่ใช้จริงคือ "ตัวพิมพ์ใหญ่/ตัวเลข/ขีดล่าง
 * ล้วน ยาว ≥3" ซึ่งพอจะแยกจากประโยคของมนุษย์ได้ (ประโยคมีช่องว่างหรือตัวพิมพ์เล็กเสมอ)
 */
const INTERNAL_CODE_SHAPE = /^[A-Z][A-Z0-9_]{2,}$/

/**
 * ถ้อยคำของ "เราไม่มีคำอธิบายให้" — ใช้ร่วมกัน 2 ทาง (ไม่มีเหตุผลติดมาเลย / รหัสภายในที่ยังไม่มีกฎ)
 *
 * 🛑 ของเดิมคือ "ไม่ทราบสาเหตุ" เฉย ๆ ซึ่งเป็นทางตัน (impeccable clarify 2026-08-23 P1-2): ผู้ขาย
 * ไม่ได้อะไรเลยจากประโยคนั้น และ **ไม่รู้ว่ากดลองใหม่ได้** ทั้งที่กิ่งนี้ส่ง `retryable: true` ⇒ ปุ่ม
 * "ลองใหม่" ขึ้นอยู่จริงบนบับเบิล ถ้อยคำจึงต้องชวนให้ใช้มัน
 *
 * 🛑 ถ้อยคำนี้ผูกกับ `retryable: true` ของทั้งสองกิ่ง — วันไหนเปลี่ยนกิ่งไหนเป็น `false` ต้องเปลี่ยน
 * คำที่นี่ด้วย ไม่งั้นจอจะขึ้นคำว่า "ส่งไม่สำเร็จ" นิ่ง ๆ แทนปุ่ม "ลองใหม่" ทั้งที่ข้อความสั่งให้กด
 *
 * "ติดต่อทีมงาน" = คำเดียวกับหน้า `/support` ไม่ได้พิมพ์สำนวนใหม่ (HR16)
 */
const NO_KNOWN_CAUSE: Copy = {
  text: 'ยังไม่รู้สาเหตุที่ส่งไม่ผ่าน — ลองส่งอีกครั้ง ถ้ายังไม่ได้ให้ติดต่อทีมงาน',
  short: 'ยังไม่รู้สาเหตุ — ลองส่งอีกครั้งได้เลย',
}

/**
 * ตัดคำนำหน้า "ส่งไม่สำเร็จ — " ออก เหลือแต่ตัวเหตุผล
 *
 * ทำไมต้องมี: บับเบิลที่ล้มเหลวมี 2 เส้นทาง — แถวที่บันทึกลง DB แล้ว (ใช้ `describeSendFailure().text`
 * ซึ่งเป็นเหตุผลล้วน) กับข้อความ optimistic ที่ยังไปไม่ถึง server (ได้ข้อความจาก `body.error` ซึ่ง
 * บางเส้นทางเติมคำนำหน้ามาแล้ว บางเส้นทางยังไม่เติม) UI วาง "ส่งไม่สำเร็จ" เป็นป้ายของตัวเองแล้ว
 * ทั้งสองเส้นทางจึงต้องส่งเข้ามาเป็นเหตุผลล้วนเหมือนกัน ไม่งั้นจะอ่านได้ว่า
 * "ส่งไม่สำเร็จ (i) ส่งไม่สำเร็จ — เกินเวลา…"
 */
export function stripSendFailurePrefix(text: string | null | undefined): string | null {
  const trimmed = (text ?? '').trim()
  if (!trimmed) return null
  if (!trimmed.startsWith(PREFIX)) return trimmed
  // ตัดทั้งคำนำหน้าและตัวคั่น (em dash พร้อมช่องว่างรอบข้าง) ถ้ามี
  const rest = trimmed.slice(PREFIX.length).replace(/^\s*—\s*/, '').trim()
  return rest || null
}

export function describeSendFailure(
  reason: string | null | undefined,
  context: SendFailureContext = {},
): SendFailureDescription {
  const raw = (reason ?? '').trim()

  const done = (
    copy: Copy,
    metaCode: number | null,
    known: boolean,
    retryable: boolean,
  ): SendFailureDescription => {
    const { text, short } = copy
    return {
      text,
      message: `${PREFIX} — ${text}`,
      short: short ?? null,
      // ผู้เรียกฝั่ง push ไม่ต้องประกอบสตริงเอง — ไม่งั้น "ใช้ short ถ้ามี" จะกลายเป็นกฎที่ก็อปไป
      // เขียนซ้ำทุก call site แล้วหลุดที่ใดที่หนึ่งโดยไม่มีอะไรฟ้อง
      shortMessage: `${PREFIX} — ${short ?? text}`,
      metaCode,
      known,
      retryable,
    }
  }

  // ไม่มีเหตุผลเลย/แถวเก่าก่อนมีคอลัมน์นี้ — ไม่รู้ว่าลองซ้ำได้ไหม ปล่อยเป็น true (ค่าเดิม)
  if (!raw) return done(NO_KNOWN_CAUSE, null, false, true)

  const m = META_CODE.exec(raw)
  const metaCode = m ? Number(m[1]) : null

  const hit = RULES.find((r) => r.match(raw, metaCode))
  if (hit) {
    // ถ้อยคำตามช่องทาง (ถ้ามี) — หยิบทั้งชุด ไม่ผสมกับชุดกลาง ดูคอมเมนต์ที่ `Rule.byChannel`
    const variant = context.channel ? hit.byChannel?.[context.channel] : undefined
    const base: Copy = variant ?? { text: hit.text, short: hit.short }

    /**
     * 🛑 override ของเธรดคอมเมนต์ **ล้าง `short` ทิ้งเสมอ** — `short` เป็นฉบับย่อ *ของ `text` ตัวเดิม*
     * ซึ่งเพิ่งถูกแทนที่ด้วยประโยคที่พูดคนละเรื่อง (เพดาน "ตอบคอมเมนต์ได้ข้อความเดียว" ไม่ใช่หน้าต่าง
     * 24 ชม.) การพา `short` เก่าไปด้วยจะได้ noti ที่ขัดกับบับเบิลของข้อความใบเดียวกัน — ยอมให้ระบบ
     * ตัดหางประโยคยาวทิ้ง ดีกว่าพูดผิดเรื่องแบบครบประโยค
     */
    const overridden = context.commentOriginNoInbound ? hit.whenCommentOrigin : undefined
    const copy: Copy = overridden ? { text: overridden } : base
    return done(copy, metaCode, true, hit.retryable ?? true)
  }

  // รหัสภายในที่ยังไม่มีกฎรองรับ — ห้ามแสดงดิบ (ดู INTERNAL_CODE_SHAPE) ตกไปคำเดียวกับกรณี
  // "ไม่มีเหตุผลติดมาเลย" เพราะทั้งสองกรณีแปลว่าเรื่องเดียวกันสำหรับผู้ขาย: เราไม่มีคำอธิบายให้
  // (ใช้คำเดิมที่มีอยู่แล้ว ไม่พิมพ์คำใหม่ — HR16). รหัสจริงยังอยู่ในคอลัมน์ `failureReason` ให้สืบได้
  if (INTERNAL_CODE_SHAPE.test(raw)) return done(NO_KNOWN_CAUSE, metaCode, false, true)

  // ไม่รู้จัก — ส่งดิบต่อไปตามเดิม ดีกว่าแปลมั่วหรือซ่อนจนสืบไม่ได้ (retryable=true ค่าเดิม — ไม่รู้ว่า
  // ลองซ้ำได้ไหมจริง แต่การปิดปุ่มโดยไม่รู้ = เดาไปอีกทาง เสี่ยงพอกัน)
  return done({ text: raw }, metaCode, false, true)
}
