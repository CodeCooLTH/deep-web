/**
 * choose-shop-copy — คำบนหน้า "เลือกร้าน" ตอนยังไม่มีร้านเลย (แก้ 2026-09-17)
 *
 * ## ปัญหาที่แก้
 *
 * คนที่ล็อกอินด้วย Apple ID ใหม่ในแอป iOS จะได้บัญชีที่ **ยังไม่มีร้านสักร้าน**
 * แล้วมาโผล่หน้านี้ · คำโปรยเดิมบอกว่า *"เริ่มขายของออนไลน์ได้ทันที"*
 * **แต่ปุ่มที่ทำสิ่งนั้นถูกซ่อนในแอป** ⇒ ผู้ใช้หาปุ่มไม่เจอ แล้วสรุปว่าแอปพัง
 *
 * ## ทำไมปุ่มถึงถูกซ่อน (และห้ามเอากลับมาเอง)
 *
 * Apple สั่งเป็นลายลักษณ์อักษรรอบ 2026-08-23:
 *
 * > "The app includes an account registration feature for businesses and organizations,
 * > which is considered access to external mechanisms for purchases or subscriptions to be
 * > used in the app. Next Steps: **Remove the account registration features for business
 * > and organizations**"
 *
 * ⇒ ในแอปเหลือได้แค่ **ล็อกอินสำหรับคนที่มีร้านอยู่แล้ว** กับ **เข้าร่วมร้านผ่านลิงก์เชิญ**
 *
 * 🛑 อย่าลืมว่าถ้าปล่อยให้กดเปิดร้านได้ จะไม่ใช่แค่ผิดกฎ — `activeShopId` จะกลายเป็นร้านส่วนตัว
 * ที่ยังไม่ตั้งค่า ⇒ `needsRegistration` เป็นจริง ⇒ **ด่าน 3.1.1 ใน `proxy.ts` ล้าง session
 * แล้วเตะออกจากระบบทันที** ซึ่งแย่กว่าทางตันเดิม
 *
 * ## 🛑 ห้ามชี้ทางไปสมัครที่เว็บ
 *
 * Apple ผูกเรื่อง "สมัครบัญชีธุรกิจ" เข้ากับ "ช่องทางไปซื้อข้างนอก" ไว้ในจดหมายฉบับเดียวกัน
 * ⇒ บอกให้ไปสมัครที่เว็บ = เดินเข้าข้อกล่าวหาเดิมตรง ๆ · คำที่ใช้ได้คือ **อธิบายตัวเอง**
 * ว่าแอปนี้มีไว้ทำอะไร ไม่ใช่ชี้ว่าให้ไปทำที่ไหนต่อ
 */

/** คำโปรยใต้หัวข้อ "ยังไม่มีร้านค้าของคุณ" */
export function chooseShopEmptySubtitle(hideOpenShop: boolean): string {
  if (hideOpenShop) {
    /* ในแอป: ไม่มีปุ่มเปิดร้าน ⇒ ต้องไม่ชวนให้หาปุ่มที่ไม่มี และไม่ชี้ไปที่อื่น */
    return 'แอปนี้สำหรับผู้ขายที่มีร้านอยู่แล้ว — ถ้ามีคนแชร์ลิงก์เชิญมาให้ วางด้านล่างเพื่อเข้าร่วมร้าน'
  }
  return 'เริ่มขายของออนไลน์ได้ทันที หรือวางลิงก์เชิญถ้ามีคนแชร์มาให้'
}
