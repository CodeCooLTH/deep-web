// round2.ts — ปัดทศนิยม 2 ตำแหน่งสำหรับ "เงิน" ทั้งระบบ
//
// สูตรนี้ถูกเขียนซ้ำเองอยู่แล้ว 5 ที่ (pnl.service, order.service ×2, OrderCreateForm,
// CartPanel) — ไฟล์นี้ตั้งขึ้นเพื่อให้ของใหม่ทุกชิ้นอ้างที่เดียว จะได้ไม่เพิ่มที่ 6
// การย้าย 5 ที่เดิมมาใช้ตัวนี้เป็นงานแยก (2 ใน 5 อยู่ในไฟล์ frontend ซึ่งต้องผ่าน ux gate)
//
// `+ Number.EPSILON` ก่อนคูณ 100 จำเป็นจริง ไม่ใช่ของประดับ: `Math.round(1.005 * 100)`
// ได้ 100 (ไม่ใช่ 101) เพราะ 1.005 เก็บใน binary float เป็น 1.00499999999999989
export const round2 = (n: number) => Math.round((n + Number.EPSILON) * 100) / 100
