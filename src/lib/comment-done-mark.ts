/**
 * comment-done-mark — เครื่องหมายถูกหน้าคอมเมนต์ที่ "จบงานแล้ว" (ส่วนขยาย 00038, 2026-08-19)
 *
 * user สั่ง: "ถ้าตอบแล้ว, ทำเครื่องหมายว่าเรียบร้อยแล้ว ให้มี icon check (คล้าย ๆ สำเร็จ)
 * ข้างหน้า comment นั้น ๆ ด้วยได้ไหม"
 *
 * 🛑 ทำไมเป็นฟังก์ชันแยกไฟล์ ไม่ใช่เทอร์นารีใน JSX: เกณฑ์ไม่ใช่ "ซับซ้อนพอไหม" แต่คือ
 * **"ถ้าเขียนกลับด้านแล้วจะมีอะไรจับได้ไหม"** — ตรรกะนี้ตัดสิน *สี* ของเครื่องหมายถูก ซึ่งเขียน
 * ผิดแล้วยังเป็น JSX ที่ถูกชนิดทุกประการ ผ่าน tsc/build/theme-guard หมด สิ่งที่ผิดคือความหมาย
 * (docs/conventions/ui-boolean-needs-a-testable-home.md)
 */

/**
 * `null`   = ยังไม่จบงาน ไม่ต้องมีเครื่องหมาย
 * `verified` = จบเพราะ **มีคำตอบจริง** (ตอบใต้คอมเมนต์ หรือทักแชทสำเร็จ) → เขียว
 * `skipped`  = จบเพราะ **คนกดข้าม/Facebook บอกว่าเคยทักไปแล้ว** ลูกค้าไม่ได้รับอะไรจากเรา → เทา
 */
export type CommentDoneMark = 'verified' | 'skipped' | null

/**
 * 🛑 รูปทรงเดียวกันแต่คนละสีโดยตั้งใจ — Verified-Means-Green ของโปรเจกต์นี้สงวนเขียวไว้กับ
 * "ข้อเท็จจริงที่ยืนยันได้" การทาเขียวให้แถวที่แค่ถูกกดข้าม = จอบอกผู้ขายว่าลูกค้าได้คำตอบแล้ว
 * ทั้งที่ไม่ได้ ซึ่งเป็นความผิดพลาดเชิงความหมาย ไม่ใช่เรื่องรสนิยม
 * (รูปทรงที่เหมือนกันยังทำให้กวาดตาอ่านว่า "จบแล้ว" ได้ในจังหวะเดียวตามที่ user ขอ)
 *
 * `answeredForReal` มาจาก server เท่านั้น — client เดาเองไม่ได้ เพราะ `state` ยุบทั้ง 3 ทางไว้
 * ในค่าเดียว แถวที่เป็นทั้ง "ตอบแล้ว" และ "ถูกกดข้าม" จะแยกไม่ออกถ้าเดาจาก `resolvedReason`
 */
export function commentDoneMark(comment: {
  state: 'UNANSWERED' | 'BOT_ANSWERED' | 'HUMAN_ANSWERED'
  answeredForReal: boolean
}): CommentDoneMark {
  if (comment.state === 'UNANSWERED') return null
  return comment.answeredForReal ? 'verified' : 'skipped'
}
