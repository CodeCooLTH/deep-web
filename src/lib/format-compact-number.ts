/**
 * format-compact-number — ย่อเลขให้อ่านง่ายบนพื้นที่แคบ (12,300 → 12.3K)
 *
 * 🛑 เดิมมี implementation เดียวกันเป๊ะ **3 ที่** (`OfficialChannels.tsx`, `ShopVideos.tsx`,
 * และแถวโชว์สินค้า) — เลขเดียวกันจึงเสี่ยงแสดงต่างกันได้ถ้ามีคนแก้เกณฑ์ทศนิยมข้างเดียว (HR16)
 *
 * 📌 ค้างไว้ให้ตัดสิน: `K`/`M` เป็นคำย่อภาษาอังกฤษ ซึ่งขัดกับแนวที่ `chat-response-display.ts`
 * ยึด (ตัด `~`/`+`/`ชม.` ทิ้งเพราะกลุ่มผู้ใช้ตาม PRODUCT.md ไม่จำเป็นต้องคุ้นสัญลักษณ์)
 * แต่มันเป็น convention ที่ใช้อยู่ทั่วแพลตฟอร์มแล้ว การเปลี่ยนกระทบกว้างกว่าหน้าโปรไฟล์
 * — คงพฤติกรรมเดิมไว้ก่อน ไม่เปลี่ยนเองในงานนี้
 */
export function compactCount(n: number): string {
  if (n < 1000) return n.toLocaleString('th-TH')
  if (n < 1_000_000) return `${(n / 1000).toFixed(n < 10_000 ? 1 : 0)}K`
  return `${(n / 1_000_000).toFixed(1)}M`
}
