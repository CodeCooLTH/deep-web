/** เงื่อนไขที่พร้อมยัดเข้า `prisma.order.findMany({ where: { shopId, ...filter } })` */
export type ThreadOrderFilter = {
  OR: ({ customerId: string } | { conversationId: string })[]
}

/**
 * resolveThreadOrderFilter — คืนเงื่อนไข "ออเดอร์ของห้องนี้" หรือ `null` เมื่อไม่มีอะไรให้ค้นเลย
 *
 * 🛑 `null` ต้องแปลว่า **ไม่ต้องยิงคิวรี** ห้ามแปลว่า "ไม่ต้องกรอง" — ถ้าผู้เรียกเผลอ spread
 * ค่าว่างเข้าไปใน `where` จะได้ออเดอร์ **ทั้งร้าน** โผล่ในแผงของห้องเดียว ซึ่งเป็นการรั่วของ
 * ข้อมูลลูกค้าคนอื่น ไม่ใช่แค่ผลลัพธ์ผิด (ผู้เรียกต้องเช็ค null ก่อนเสมอ — มีเทสปักหมุดไว้)
 */
export function resolveThreadOrderFilter(input: {
  /** ลูกค้าที่เธรดผูกอยู่ ณ ตอนนี้ (null = ยังไม่เคยผูก / เพิ่งถูกย้ายไปคนอื่น) */
  customerId: string | null | undefined
  /** ห้องแชทนี้ — ใบที่ถูกเปิดจากห้องนี้ต้องอยู่ในห้องนี้ตลอดไป ไม่ว่าเบอร์จะถูกแก้กี่รอบ */
  conversationId: string | null | undefined
}): ThreadOrderFilter | null {
  const or: ThreadOrderFilter['OR'] = []
  if (input.customerId) or.push({ customerId: input.customerId })
  if (input.conversationId) or.push({ conversationId: input.conversationId })
  return or.length > 0 ? { OR: or } : null
}
