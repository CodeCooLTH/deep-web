/**
 * link-conflict — ตัดสินว่า "Apple/Facebook/LINE ID นี้มีเจ้าของแล้ว จะทำยังไงต่อ"
 *
 * ## ปัญหาที่ไฟล์นี้เกิดมาแก้ (เจอจริงบน prod 2026-08-15)
 *
 * ผู้ใช้ที่มีบัญชี Deep อยู่แล้ว กดปุ่ม "เข้าสู่ระบบด้วย Apple" ที่หน้าล็อกอินโดยไม่ตั้งใจ —
 * บนมือถือ Face ID อนุมัติให้ในวินาทีเดียวโดยไม่ต้องกรอกอะไรเลย ผู้ใช้จึงคิดว่า "ยังไม่ได้ทำอะไร"
 * แต่ระบบสร้างบัญชีใหม่ให้เรียบร้อยแล้ว แล้วเขาก็ตันทุกทาง:
 *
 *   - ถอดการเชื่อม → ต้องยืนยันด้วย OTP ทางเบอร์ **แต่บัญชีค้างไม่มีเบอร์**
 *   - ใส่เบอร์ → เบอร์เป็นของบัญชีจริงไปแล้ว ("เบอร์นี้มีบัญชีแล้ว")
 *   - ลบบัญชีค้างเอง → ปุ่มอยู่ที่ /account แต่ proxy ขังไว้ที่ /register ทุก route
 *   - เอา Apple ID ไปเชื่อมบัญชีจริง → `link_error=taken` ถาวร
 *
 * ⇒ **กดพลาดครั้งเดียว = Apple ID นั้นใช้กับ Deep ไม่ได้อีกเลย** และผู้ใช้แก้เองไม่ได้สักทาง
 *
 * ## กติกา
 *
 * คนที่พิสูจน์ได้ว่าคุม Apple ID ตัวนั้น **คือเจ้าของตัวตนนั้น** — เขาเพิ่งผ่าน Apple มาเมื่อกี้
 * การให้เขาย้ายตัวตนของตัวเองออกจากบัญชีที่ไม่มีอะไรอยู่ จึงไม่ใช่การยึดของคนอื่น
 *
 * แต่ถ้าบัญชีปลายทาง **มีตัวตนจริง** (ยืนยันเบอร์แล้ว / ตั้งรหัสผ่านแล้ว / เปิดร้านจริงแล้ว)
 * ห้ามแตะเด็ดขาด — ยึดไปแปลว่าอาจทำลายกิจการของคนอื่นทั้งใบ ให้เจ้าตัวไปจัดการเองเท่านั้น
 *
 * 🛑 **ตรรกะนี้ต้องอยู่ในฟังก์ชันบริสุทธิ์ ห้ามฝังใน `auth.ts`** ตาม
 * `docs/conventions/ui-boolean-needs-a-testable-home.md` — เกณฑ์ไม่ใช่ "ซับซ้อนพอไหม" แต่คือ
 * "ถ้าเขียนกลับด้านแล้วจะมีอะไรจับได้ไหม" และการกลับด้านที่นี่แปลว่า **ลบบัญชีจริงของคนอื่นทิ้ง**
 */

export type LinkConflictVerdict =
  /** ยึดคืนได้ — บัญชีเดิมไม่มีตัวตนจริง ย้ายการเชื่อมมาให้บัญชีที่ขอ แล้วปิดบัญชีเดิม */
  | 'RECLAIM'
  /** บัญชีเดิมถูกลบไปแล้ว — ย้ายการเชื่อมได้ แต่ไม่ต้องปิดซ้ำ */
  | 'RECLAIM_DELETED'
  /** ห้ามแตะ — บัญชีเดิมมีตัวตนจริง ให้เจ้าตัวไปถอด/ลบเอง */
  | 'BLOCKED'

/**
 * ข้อมูลของ "บัญชีที่ถือ OAuth id นั้นอยู่" เท่าที่จำเป็นต่อการตัดสิน
 *
 * ทุก field ต้องส่งมาให้ครบเสมอ — ห้ามให้ optional เพราะ field ที่ลืมส่งจะกลายเป็น `undefined`
 * ซึ่ง falsy แล้วถูกอ่านว่า "ไม่มีตัวตน" ⇒ เผลอตัดสินให้ยึดบัญชีจริงของคนอื่น
 */
export interface LinkConflictHolder {
  /** ถูกลบไปแล้วหรือยัง (soft delete) */
  deletedAt: Date | null
  /** ยืนยันเบอร์แล้ว — ตัวชี้ขาดที่สุดว่ามีตัวตนจริง (เบอร์ตั้งได้ครั้งเดียว เปลี่ยนไม่ได้) */
  phone: string | null
  /** ตั้งรหัสผ่านเองแล้ว = ตั้งใจใช้บัญชีนี้ */
  passwordHash: string | null
  /** จำนวนร้านที่ตั้ง slug แล้ว (ลงทะเบียนจบเฟส 2) — ยังไม่นับร้านที่ยังไม่มี slug */
  completedShopCount: number
  /** จำนวนออเดอร์ของร้านทั้งหมดในบัญชีนี้ — มีออเดอร์ = มีคู่ค้าที่ได้รับผลกระทบ */
  orderCount: number
  /** เป็นสมาชิก (ADMIN) ของร้านคนอื่นกี่ร้าน — มี = มีคนเชิญเขาเข้าไปทำงานจริง */
  shopMemberCount: number
  /** ผูก OAuth เจ้าอื่นไว้ด้วยกี่เจ้า (ไม่นับเจ้าที่กำลังจะย้าย) — มี = เคยตั้งใจใช้บัญชีนี้ */
  otherAuthAccountCount: number
}

/**
 * ตัดสินว่าจะยึดคืนได้ไหม
 *
 * 🛑 **fail-closed** — ค่าใดค่าหนึ่งบ่งชี้ว่ามีตัวตนจริง = `BLOCKED` ทันที
 * ไม่ใช่ "ถ้าครบทุกข้อถึงจะบล็อก" เพราะการเดาผิดฝั่งนี้แปลว่าลบข้อมูลของคนอื่น
 */
export function classifyLinkConflict(holder: LinkConflictHolder): LinkConflictVerdict {
  // บัญชีที่ถูกลบไปแล้วไม่ควรถือตัวตนของใครไว้ต่อ — ปล่อยคืนได้เสมอ ไม่ต้องดูเงื่อนไขอื่น
  // (เจ้าของเดิมล็อกอินกลับเข้าไม่ได้อยู่แล้ว `isDeletedUser` บล็อกไว้ทุก provider)
  if (holder.deletedAt !== null) return 'RECLAIM_DELETED'

  const hasIdentity =
    holder.phone !== null ||
    holder.passwordHash !== null ||
    holder.completedShopCount > 0 ||
    holder.orderCount > 0 ||
    holder.shopMemberCount > 0 ||
    holder.otherAuthAccountCount > 0

  return hasIdentity ? 'BLOCKED' : 'RECLAIM'
}

/**
 * ยึดคืนแล้วต้องปิดบัญชีเดิมด้วยไหม
 *
 * `RECLAIM_DELETED` ไม่ต้องปิดซ้ำ — ปิดไปแล้ว และการเขียน `deletedAt` ทับจะทำให้
 * นาฬิกา retention (วันที่จะลบข้อมูลจริง) ถูกรีเซ็ตย้อนหลัง ซึ่งยืดเวลาเก็บข้อมูลของคนที่
 * ขอให้ลบไปแล้วออกไปอีก — ผิดเจตนาของฟีเจอร์ลบบัญชี (App Store 5.1.1(v))
 */
export function shouldCloseHolder(verdict: LinkConflictVerdict): boolean {
  return verdict === 'RECLAIM'
}
