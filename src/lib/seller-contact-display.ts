/**
 * ข้อมูลติดต่อที่ผู้ขายเห็น — คืนค่าดิบเสมอ
 *
 * @param fallback ข้อความแทนตอนไม่มีข้อมูล (แต่ละหน้าใช้คำต่างกันอยู่แล้ว เช่น '—' หรือ
 *   'ไม่ระบุ' ที่แปลตามภาษา) — ไม่บังคับให้เหมือนกันเพราะเป็นเรื่องของหน้า ไม่ใช่ของข้อมูล
 */
export function sellerContactDisplay(contact: string | null | undefined, fallback = '—'): string {
  const value = (contact ?? '').trim()
  return value || fallback
}

/** เวอร์ชันที่คืน null เมื่อไม่มีข้อมูล — สำหรับที่ที่ต้องแยก "ไม่มี" ออกจาก "ข้อความว่าง" */
export function sellerContactOrNull(contact: string | null | undefined): string | null {
  const value = (contact ?? '').trim()
  return value || null
}
