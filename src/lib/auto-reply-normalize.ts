// ⇒ ทุกครั้งที่แก้ไฟล์นี้ **ต้องเขียน migration/สคริปต์ backfill `normalizedPhrase` ทั้งตาราง
//   แล้ว deploy พร้อมกันในรอบเดียว** (`npm run backfill:auto-reply-phrases` ตาม SRS TFR-003) —
//   ห้าม deploy โค้ดใหม่ก่อนแล้วค่อยตามด้วย backfill ทีหลัง
//
// คุณสมบัติที่ต้องคงไว้เสมอ (มี unit test บังคับ): pure (ไม่มี I/O ไม่มี state),
// deterministic, idempotent — normalizeMessage(normalizeMessage(x)) === normalizeMessage(x)

/**
 * ปรับข้อความดิบให้เป็นรูปมาตรฐานสำหรับเปรียบเทียบ keyword (SRS TFR-007)
 *
 * ลำดับขั้นตอน (ห้ามสลับ — ผลลัพธ์ผิดทันทีถ้าสลับ):
 *   1. null/undefined -> ""
 *   2. Unicode NFC (ต้องมาก่อนทุกขั้น ไม่งั้นขั้นถัดไปเทียบ char-class ไม่ตรง)
 *   3. รวมชนิดช่องว่าง (\t\n\r\f\v, NBSP, ZWSP, ideographic space, BOM) -> " "
 *   4. lowercase (มีผลเฉพาะอังกฤษ; ภาษาไทยไม่มีผล)
 *   5. ลบทิ้งกลุ่มวรรคตอน/เครื่องหมายประดับ + emoji/symbol
 *   6. แทนกลุ่มตัวคั่นคำ (ขอบเขตคำจริงของอังกฤษ เช่น cash-on-delivery) ด้วยช่องว่าง
 *   7. ยุบช่องว่างซ้ำเหลือตัวเดียว
 *   8. ตัดช่องว่างหัวท้าย
 *
 * [ข้อห้าม] ห้ามตัดวรรณยุกต์ไทย (่-๋)/สระ (ะ-ฺ, ็, ์-๎)/ไม้ไต่คู้-ทัณฑฆาต — AC-002-05 บังคับว่า
 * ต้องรองรับข้อความไทยที่มีวรรณยุกต์/สระครบถ้วน (ตัดแล้ว "ข้าว"="ขาว" ทำลาย EXACT)
 */
export function normalizeMessage(input: string | null | undefined): string {
  if (input == null) return ''

  // ขั้น 2: Unicode NFC — ให้ทุกขั้นถัดไปเห็นรูปอักขระเดียวกันเสมอ (AC-010-04)
  let s = input.normalize('NFC')

  // ขั้น 3: รวมชนิดช่องว่างที่ไม่ใช่ " " ปกติเป็น " " ก่อน — กัน NBSP/ZWSP ที่ลูกค้าคัดลอกมา
  // ซึ่ง \s ปกติจับได้บางตัว แต่ NBSP( )/ZWSP(​)/ideographic space(　)/BOM(﻿)
  // ต้องระบุตรงตัว (AC-010-01)
  s = s.replace(/[\t\n\r\f\v ​　﻿]/g, ' ')

  // ขั้น 4: lowercase อังกฤษ — ทำก่อนขั้นวรรคตอนเพื่อให้ char-class ที่เทียบเป็นชุดเดียว (AC-010-02)
  s = s.toLowerCase()

  // ขั้น 5: ลบทิ้ง — วรรคตอน/เครื่องหมายประดับ + emoji/symbol (AC-010-03, AC-010-05)
  // ไม่แตะช่วงวรรณยุกต์/สระไทยใด ๆ โดยตั้งใจ (ดูคำเตือนบนหัวไฟล์)
  s = s.replace(
    /[!?.,;:"'`~*#()\[\]{}…‼⁉ๆฯ๏๚๛！？。、\u{FE0F}\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}]/gu,
    ''
  )

  // ขั้น 6: ตัวคั่นคำ (ขอบเขตคำจริงของอังกฤษ) -> แทนด้วยช่องว่าง (AC-010-03)
  s = s.replace(/[-–—_/\\|+=@&]/g, ' ')

  // ขั้น 7: ยุบช่องว่างซ้ำ (ที่ขั้น 5-6 อาจสร้างเพิ่ม) เหลือตัวเดียว
  s = s.replace(/\s+/g, ' ')

  // ขั้น 8: ตัดหัวท้ายเสมอ (ขั้นสุดท้าย)
  return s.trim()
}
