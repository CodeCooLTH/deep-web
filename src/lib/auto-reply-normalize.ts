//   1) ตอนเขียน `AutoReplyPhrase.normalizedPhrase` (TFR-003)
//   2) ตอนเทียบข้อความลูกค้าเข้ามาใหม่ (TFR-008)
// ถ้าแก้พฤติกรรมฟังก์ชันนี้เมื่อไหร่ (เพิ่ม/ลด/สลับลำดับขั้นตอน) ค่าที่เก็บไว้ใน
// `AutoReplyPhrase.normalizedPhrase` ของทุกร้านจะ "stale" ทันที (TD-011, SRS §8 R-3) —
// กลุ่มคำที่ร้านตั้งไว้เดิมจะ match ไม่ตรงกับข้อความลูกค้าแบบเงียบ ๆ หาสาเหตุยากมาก
