/**
 * iap-verify-outcome — หลังยิง `/api/iap/apple/verify` แล้วต้องทำอะไรต่อ (feature 00064)
 *
 * ## 🛑 ทำไมต้องเป็นฟังก์ชันเดียวที่ทุกที่ใช้ร่วมกัน
 *
 * กติกานี้ตัดสิน **เงินของลูกค้า** และมีผู้ใช้ 2 ราย (หน้าเลือกแพ็กเกจ · ตัวกู้คืนอัตโนมัติ)
 * ถ้าเขียนแยกกันแล้ววันหนึ่งมีคนแก้ที่เดียว ผลคือธุรกรรมถูกปิดทิ้งในเส้นทางหนึ่งแต่ไม่ปิดในอีก
 * เส้นทางหนึ่ง — Hard Rule 16 ตรงตัว (ของสิ่งเดียวกัน สองนิยาม)
 *
 * ## กติกา
 *
 * | ผลจากเซิร์ฟเวอร์ | ปิดธุรกรรม? | ทำไม |
 * |---|---|---|
 * | 2xx | **ปิด** | เปิดสิทธิ์แล้ว ไม่ต้องให้ StoreKit ส่งกลับมาอีก |
 * | 4xx | **ปิด** | ใบนี้ใช้ไม่ได้จริง ลองกี่ครั้งก็เท่าเดิม · ไม่ปิด = เด้ง error ใส่หน้าผู้ใช้ทุกครั้งที่เปิดแอปตลอดไป |
 * | 5xx | **ไม่ปิด** | ฝั่งเราเพี้ยนชั่วคราว ลองใหม่ได้ |
 * | เน็ตหลุด (ยิงไม่ถึง) | **ไม่ปิด** | ยังไม่มีใครตัดสินใจอะไรเลย |
 *
 * 🛑 **"ปิดธุรกรรม" ไม่ได้แปลว่า "สำเร็จ"** — 4xx ปิดเหมือน 2xx แต่ไม่ได้สิทธิ์
 * สองคำถามนี้แยกกันเสมอ (`shouldFinish` กับ `granted`) ใครยุบให้เหลือธงเดียวคือกำลังทำให้
 * ใบที่ถูกปฏิเสธถูกนับเป็นการซื้อสำเร็จ
 */

/** ผลจากการยิงไปหาเซิร์ฟเวอร์ — `'NETWORK_ERROR'` = ยิงไม่ถึงเลย (ไม่มี status ให้ดู) */
export type VerifyResponse = { status: number } | 'NETWORK_ERROR'

export interface VerifyOutcome {
  /** สั่ง StoreKit ปิดธุรกรรมไหม — ปิดแล้วมันจะไม่ถูกส่งกลับมาอีกตลอดกาล */
  shouldFinish: boolean
  /** เปิดสิทธิ์สำเร็จไหม — **ไม่ใช่ตัวเดียวกับ `shouldFinish`** */
  granted: boolean
}

export function decideVerifyOutcome(res: VerifyResponse): VerifyOutcome {
  if (res === 'NETWORK_ERROR') return { shouldFinish: false, granted: false }

  if (res.status >= 200 && res.status < 300) return { shouldFinish: true, granted: true }

  /* 5xx (และอะไรก็ตามที่ ≥500) = ฝั่งเราเพี้ยน ลองใหม่ได้ ⇒ ห้ามปิด */
  if (res.status >= 500) return { shouldFinish: false, granted: false }

  /* เหลือ 3xx/4xx — ใบนี้ใช้ไม่ได้จริง ปิดทิ้งไม่ให้วนกลับมาหลอน แต่ไม่ได้สิทธิ์ */
  return { shouldFinish: true, granted: false }
}
