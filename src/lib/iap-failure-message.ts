/**
 * iap-failure-message — คำที่ผู้ใช้เห็นเมื่อคำขอฝั่ง Apple ไม่สำเร็จ (feature 00064)
 *
 * แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพราะเดิมอยู่ในตัว component ⇒ ไม่มีเทสไหนแตะได้เลย
 * (รีโปนี้ไม่มี jsdom) ตรงตาม `docs/conventions/ui-boolean-needs-a-testable-home.md`
 *
 * ## 🛑 ทำไม `context` ถึงเป็นพารามิเตอร์บังคับ ไม่มีค่าปริยาย
 *
 * `TIMEOUT` **แปลคนละอย่างในแต่ละบริบท** และการแปลผิดทำให้ผู้ใช้ทำสิ่งที่เสียหาย:
 *
 * - ตอนขอราคา — ไม่มีคนอยู่ในวงจร ⇒ หมดเวลา = สะพานไป native พัง/เก่าจริง ๆ
 *   คำที่ถูกคือ "แอปไม่ตอบสนอง ลองใหม่"
 * - **ตอนกดซื้อ — หมดเวลา ≠ ไม่ได้จ่ายเงิน** ผู้ใช้อาจยืนยันกับ Apple สำเร็จไปแล้วหลัง
 *   เราเลิกรอ (ธุรกรรมค้างอยู่ที่ StoreKit) ⇒ บอกให้ "ลองใหม่" คือชวนให้กดซื้อซ้ำ
 *   ทางที่ถูกคือชี้ไปที่ปุ่ม **กู้คืนการซื้อ** ซึ่งอยู่ในหน้าเดียวกันอยู่แล้ว
 *
 * ค่าปริยายคือสิ่งที่ทำให้บั๊กแบบนี้เกิด — บังคับให้ระบุ แล้วปล่อยให้ `tsc` ไล่ผู้เรียกให้ครบ
 * (ท่าเดียวกับ `describeProgress()` ที่เคยส่งคำของผู้ขายไปโผล่หน้าผู้ซื้อ)
 */
import type { IapFailure } from '@/lib/iap-bridge-protocol'

/** คำขอที่ล้มเหลวมาจากจังหวะไหน — ตัวตัดสินว่า `TIMEOUT` แปลว่าอะไร */
export type IapFailureContext = 'products' | 'purchase' | 'restore'

export function iapFailureMessage(reason: IapFailure, context: IapFailureContext): string {
  switch (reason) {
    case 'CANCELLED':
      return 'ยกเลิกการซื้อแล้ว'

    case 'TIMEOUT':
      if (context === 'purchase') {
        /* ห้ามมีคำว่า "ลองใหม่" — ดูเหตุผลหัวไฟล์ */
        return 'ยังไม่ได้รับผลจาก App Store — ถ้าชำระเงินไปแล้ว ให้กด "กู้คืนการซื้อ" ด้านล่าง'
      }
      if (context === 'restore') {
        return 'ยังไม่ได้รับผลจาก App Store กรุณาลองใหม่อีกครั้ง'
      }
      return 'แอปไม่ตอบสนอง กรุณาลองใหม่อีกครั้ง'

    case 'UNAVAILABLE':
      return 'ตอนนี้ซื้อในแอปไม่ได้ กรุณาลองใหม่ภายหลัง'

    case 'FAILED':
      return 'ทำรายการไม่สำเร็จ กรุณาลองใหม่อีกครั้ง'
  }
}

