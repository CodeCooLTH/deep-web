/**
 * `?date=` ของหน้า `/queues` — นิยามเดียวของ "ค่าที่รับได้" ทั้งมือถือและเดสก์ท็อป (HR16)
 *
 * ## ที่มา
 *
 * ไทล์ "นัดวันนี้ N" บนหน้าแรกเคยชี้ `/queues` เปล่า ๆ ⇒ เปิดมาเจอ **ปฏิทินทั้งเดือน**
 * ต้องจิ้มหาวันเอง ทั้งที่ป้ายบนไทล์สัญญาว่าจะพาไปดูงาน "ของวันนี้"
 * (หัวหน้าแจ้ง 2026-08-19: *"กดนัดวันนี้ มันไม่เข้าไปที่ตารางงานของวันนี้ด้วย
 * มันไปโผล่หน้า calendar รวม"*)
 *
 * ## 🛑 ทำไมต้องกรอง ไม่ใช่ส่งค่าดิบเข้าปฏิทิน
 *
 * ค่านี้มาจาก URL ⇒ ใครพิมพ์อะไรมาก็ได้ `new Date('abc')` คือ `Invalid Date` ซึ่ง
 * **ไม่ throw** แต่ทำให้ปฏิทินเรนเดอร์เพี้ยนเงียบ ๆ — ต้องตกเป็น `null` แล้วให้ทั้งสองฝั่ง
 * ถอยไปพฤติกรรมเดิม (เปิดที่เดือนปัจจุบัน / ไม่เปิดชีต) ซึ่งเป็นค่าที่ถูกอยู่แล้ว
 *
 * รูปแบบตายตัวไม่พอ — `2026-02-31` ผ่าน regex ทุกตัวอักษรแต่ไม่มีอยู่จริงในปฏิทิน
 * จึงต้องประกอบวันกลับมาเทียบว่าตรงกับที่รับมาไหม (JS จะม้วน 02-31 ไปเป็น 03-03 ให้เอง)
 */
export function parseQueueDateParam(raw: string | null | undefined): string | null {
  if (!raw || !/^\d{4}-\d{2}-\d{2}$/.test(raw)) return null
  const [y, m, d] = raw.split('-').map(Number)
  // เที่ยงวัน ไม่ใช่เที่ยงคืน — กัน DST/ออฟเซ็ตดันวันเลื่อนตอนประกอบกลับ
  const probe = new Date(y, m - 1, d, 12)
  const same =
    probe.getFullYear() === y && probe.getMonth() === m - 1 && probe.getDate() === d
  return same ? raw : null
}
