/**
 * กฎ "เธรดแชทนี้ผูกกับลูกค้าคนไหน" — จุดเดียวของความจริง
 *
 * ที่มา (user report 2026-08-10): แอดมินกด "แก้ไข" ออเดอร์ในโมดัลของห้องแชท แล้วแก้เบอร์โทรที่คีย์ผิด
 * ผลคือ **ออเดอร์หายไปจากห้องแชทนั้นทั้งใบ** ทั้งที่ตั้งใจแค่แก้เบอร์ของลูกค้าคนนี้
 *
 * กลไก: `Customer.phone` เป็น unique ทั้งระบบ → เบอร์ใหม่ = Customer คนละแถว → `updateOrder`
 * ย้าย `Order.customerId` ไปคนใหม่ (ถูกแล้ว — ออเดอร์ควรอยู่กับเบอร์ที่ถูกต้อง) แต่แผงออเดอร์ใน
 * ห้องแชทดึงข้อมูลด้วย `ExternalContact.customerId` ของเธรดล้วน ๆ ซึ่งยังชี้คนเก่า → ผลลัพธ์ว่างเปล่า
 * ไม่มี error ไม่มีอะไรฟ้อง (ทุกแถวยังอยู่ครบใน `/orders`) — หน้าจอแค่ถามคำถามที่ไม่มีใครตอบว่า
 * "ออเดอร์ของลูกค้าคนเก่ามีอะไรบ้าง" ทั้งที่คนใช้งานกำลังถามว่า "ออเดอร์ในห้องนี้มีอะไรบ้าง"
 *
 * 🛑 ทำไมต้องเป็นฟังก์ชันกลาง ไม่ใช่เขียนที่ `updateOrder` จุดเดียวตามที่ถูกรายงาน: ทางเข้าที่เขียน
 * `Order.customerId` มี 2 ทาง และ **ทางสร้างใหม่ก็มีอาการเดียวกัน** — เธรดที่ผูกลูกค้าไว้แล้ว พอสร้าง
 * ออเดอร์ใหม่ด้วยเบอร์อื่น ใบใหม่ก็ไม่โผล่ในแผงเช่นกัน (`createOrder` ผูกให้เฉพาะตอน `customerId=null`)
 * คอมเมนต์เดิมที่นั่นเขียนเจตนาไว้ว่า "login ชนะ manual" แต่เงื่อนไขที่เขียนจริงกว้างกว่านั้นมาก คือ
 * "ไม่ทับอะไรเลยสักกรณี" — ตัวนี้คือเจตนาเดิมที่เขียนให้ตรงกับสิ่งที่โค้ดทำ
 */

export interface ThreadCustomerLinkInput {
  /** Customer ที่ ExternalContact ของเธรดผูกอยู่ตอนนี้ (null = ยังไม่เคยผูก) */
  linkedCustomerId: string | null | undefined
  /**
   * `Customer.userId` ของคนที่ผูกอยู่ — ไม่ null แปลว่าลิงก์นี้มาจาก "ผู้ซื้อ login เข้ามาเอง"
   * ซึ่งเป็นตัวตนที่ยืนยันแล้ว ห้ามให้การคีย์เบอร์ของแอดมินไปทับ (login ชนะ manual)
   */
  linkedCustomerUserId: string | null | undefined
  /** Customer ที่ได้จากเบอร์บนออเดอร์ใบที่กำลังบันทึก */
  newCustomerId: string
}

export function shouldRelinkThreadCustomer(input: ThreadCustomerLinkInput): boolean {
  // ยังไม่เคยผูก → ผูกเลย (พฤติกรรมเดิมของ createOrder ตั้งแต่ 2026-07-24)
  if (!input.linkedCustomerId) return true
  // คนเดิมอยู่แล้ว → ไม่ต้องเขียนซ้ำ (กัน write เปล่า + กัน updatedAt ขยับโดยไม่มีอะไรเปลี่ยน)
  if (input.linkedCustomerId === input.newCustomerId) return false
  // ผูกจากการ login ของผู้ซื้อ = ตัวตนที่ยืนยันแล้ว ห้ามแตะ
  return !input.linkedCustomerUserId
}
