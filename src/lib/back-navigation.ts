/**
 * ตัดสินว่าปุ่ม "ย้อนกลับ" ควรทำอะไรกับประวัติเบราว์เซอร์
 *
 * ## บั๊กที่ไฟล์นี้มีไว้แก้ (user เจอเองบน prod 2026-08-23)
 *
 * *"กดย้อนกลับที่หน้าแก้ไขออเดอร์ → มาหน้ารายละเอียด → กดย้อนกลับ → กลับไปหน้าแก้ไขอีก วนลูป"*
 *
 * วงจรที่เกิด (ทุกขั้นคือ entry ในประวัติ):
 *
 * ```
 * [.. , รายละเอียด]                     ← ผู้ใช้อยู่ตรงนี้
 *   กด "แก้ไข"  → push
 * [.. , รายละเอียด, แก้ไข]              ← อยู่ที่หน้าแก้ไข
 *   กดย้อนกลับ  → push(รายละเอียด)      ← 🛑 ตรงนี้คือตัวปัญหา
 * [.. , รายละเอียด, แก้ไข, รายละเอียด]  ← อยู่ที่รายละเอียด "ใบใหม่"
 *   กดย้อนกลับ  → back()
 * [.. , รายละเอียด, แก้ไข]              ← กลับเข้าหน้าแก้ไข 🔁
 * ```
 *
 * 🛑 **ต้นเหตุคือปุ่มย้อนกลับใช้ `push`** — `push` แปลว่า "ไปข้างหน้าอีกหน้าหนึ่ง" ซึ่งตรงข้าม
 * กับสิ่งที่ปุ่มนี้สัญญากับผู้ใช้ · พอหน้าปลายทาง (รายละเอียดออเดอร์) ใช้ `back()` ตามปกติ
 * สองหน้าจึงผลักกันไปมาไม่รู้จบ — **ฝั่งหนึ่งดันเข้า อีกฝั่งดึงออก**
 *
 * หลักฐานยืนยันว่าตัวการคือ `backHref` ไม่ใช่อย่างอื่น: **หน้าแก้ไขสินค้า
 * (`products/[id]/edit`) ไม่ส่ง `backHref` เลย จึงใช้ `back()` และ *ไม่มีอาการนี้*** —
 * โครงหน้าเหมือนกันทุกอย่าง ต่างกันแค่ prop ตัวนี้ตัวเดียว
 *
 * ## ทำไมไม่มี gate ไหนจับได้
 *
 * `router.push(href)` เป็นโค้ดที่ถูกต้องทุกตัวอักษร · `tsc`/build/eslint/เทสผ่านหมด
 * สิ่งที่ผิดคือ **ความหมาย** ของการกระทำเทียบกับชื่อปุ่ม ซึ่งไม่มีเครื่องมือไหนอ่านออก
 * (คลาสเดียวกับ `ui-boolean-needs-a-testable-home.md` — จึงยกออกมาเป็นฟังก์ชันบริสุทธิ์ที่นี่
 * เพื่อให้มีที่ให้เทสจับ แทนที่จะฝังเป็น if กลาง component)
 */

/** สิ่งที่ผู้เรียกต้องไปสั่ง router ต่อ — แยกจากตัว router เพื่อให้เทสได้โดยไม่ต้องมีเบราว์เซอร์ */
export type BackNavigation =
  /** ถอยประวัติหนึ่งขั้น — **ไม่เพิ่ม entry** จึงไม่มีทางวนลูป */
  | { action: 'back' }
  /** แทนที่ entry ปัจจุบัน — ไปปลายทางที่กำหนดโดย **ไม่เพิ่ม entry** */
  | { action: 'replace'; href: string }
  /** เพิ่ม entry ใหม่ — ใช้เฉพาะตอนไม่มีประวัติให้ถอย (เปิดลิงก์ตรงเข้ามา) */
  | { action: 'push'; href: string }

export type BackNavigationInput = {
  /**
   * ปลายทาง **ตายตัว** — ไปที่นี่เสมอไม่ว่าจะมาจากไหน (เช่น `orders/new` → `/orders`)
   *
   * 🛑 สั่ง `replace` ไม่ใช่ `push` — ปลายทางตายตัวคือเรื่องของ *จะไปไหน* ไม่ใช่ใบอนุญาต
   * ให้เพิ่ม entry · `push` ที่นี่คือสิ่งที่ทำให้เกิดลูปในหน้าแก้ไขออเดอร์
   */
  backHref?: string
  /**
   * ปลายทาง **สำรอง** — ถอยประวัติก่อนเสมอ ใช้ค่านี้ต่อเมื่อไม่มีอะไรให้ถอย
   *
   * ใช้กับหน้าที่มีทางเข้าหลายทาง (หน้าแก้ไขออเดอร์เข้าได้ทั้งจากรายละเอียดและจากรายการ)
   * — "ย้อนกลับ" ของหน้าพวกนี้แปลว่า *กลับไปที่ที่เพิ่งมา* ซึ่งมีแต่ประวัติที่รู้
   */
  backFallbackHref?: string
  /** `window.history.length` — ≤1 แปลว่าเปิดลิงก์นี้ขึ้นมาตรง ๆ ไม่มีอะไรให้ถอย */
  historyLength: number
}

/** ปลายทางสุดท้ายเมื่อไม่มีทั้งประวัติและ href ที่ผู้เรียกกำหนด */
export const BACK_LAST_RESORT_HREF = '/dashboard'

export function resolveBackNavigation({
  backHref,
  backFallbackHref,
  historyLength,
}: BackNavigationInput): BackNavigation {
  /**
   * 🛑 ปลายทางตายตัวมาก่อน และเป็น `replace` เสมอ — ไม่ว่าจะมีประวัติหรือไม่
   * (ถ้าเผลอทำเป็น `push` ตอนมีประวัติ ลูปเดิมจะกลับมาทันทีโดยไม่มีอาการอื่นให้สังเกต)
   */
  if (backHref) return { action: 'replace', href: backHref }

  /* มีอะไรให้ถอย = ถอย · เป็นทางเดียวที่ **ลดขนาดประวัติ** จึงไม่มีทางวนลูปตามนิยาม */
  if (historyLength > 1) return { action: 'back' }

  /* ไม่มีประวัติ = เปิดลิงก์เข้ามาตรง ๆ · `back()` ตรงนี้จะพาออกจากแอปไปเลย */
  return { action: 'push', href: backFallbackHref ?? BACK_LAST_RESORT_HREF }
}
