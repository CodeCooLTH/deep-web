/**
 * เปลี่ยนไหม — นับเมื่อ **ชุดรูปต่างกัน** หรือ **รูปปกเปลี่ยน**
 *
 * 🛑 ข้อนี้ยังเป็น Open Question ของ 00060 (OQ-3: สลับลำดับล้วน/ลบออกอย่างเดียว นับไหม)
 *    ที่เลือกไว้ตรงนี้คือจุดกึ่งกลางที่ตอบทั้งสองเหตุผลที่กฎมีอยู่:
 *      - **ชุดต่างกัน** ⇒ มีรูปที่ไม่เคยถูกตรวจโผล่เข้ามา (หรือรูปที่ถูกตรวจหายไป)
 *      - **รูปปกเปลี่ยน** ⇒ สิ่งที่ผู้ซื้อเห็นเป็นอย่างแรกเปลี่ยน แม้ชุดรูปจะเท่าเดิม
 *    ส่วนการสลับลำดับรูปที่ไม่ใช่ปก **ไม่นับ** เพราะไม่มีรูปใหม่เข้ามาและปกยังเป็นใบเดิม
 *    ⇒ ถ้ามติออกมาต่างจากนี้ **แก้ที่ฟังก์ชันนี้ฟังก์ชันเดียว** ห้ามไปแก้ที่ผู้เรียก
 */
export function roomListingImagesChanged(prev: readonly string[], next: readonly string[]): boolean {
  if (prev.length !== next.length) return true
  // รูปปกคือใบแรกเสมอ (ตาม schema ของ Room.images)
  if ((prev[0] ?? null) !== (next[0] ?? null)) return true
  const a = [...prev].sort()
  const b = [...next].sort()
  return a.some((v, i) => v !== b[i])
}
