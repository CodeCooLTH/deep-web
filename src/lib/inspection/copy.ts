//
// 🛑 ข้อความยืนยันการยกเลิกต้องมาจากที่เดียวกับข้อความในกล่องยืนยัน**ก่อนกด** (Hard Rule 16)
//    สองที่เขียนเองจะกลายเป็นคำสัญญาสองแบบในจอเดียว และคำสัญญาที่ต่างกันเรื่อง "คืนเงินไหม"
//    คือสิ่งที่ร้านจะยกมาอ้างตอนทักท้วง

import { formatDateTH } from '@/lib/format-date'

/**
 * ข้อความแจ้งผลของการยกเลิกแผน — ต้องพูดครบ 3 อย่างเสมอ: วันสิ้นสุด · ประวัติยังอยู่ ·
 * ไม่คืนเงิน (ตัดข้อใดข้อหนึ่งออกแปลว่าเราปล่อยให้ร้านเข้าใจผิดในเรื่องที่เขาจะทักท้วงภายหลัง)
 */
export function cancelInspectionNoticeTh(effectiveAt: Date): string {
  return (
    `แผนการตรวจสอบจะสิ้นสุดวันที่ ${formatDateTH(effectiveAt)} ` +
    'หลังจากนั้นโปรไฟล์จะแสดงว่าไม่ได้อยู่ในแผนการตรวจสอบแล้ว ' +
    'ประวัติรอบตรวจเดิมยังแสดงอยู่ครบ และค่าตรวจที่ชำระไปแล้วไม่มีการคืนเงิน'
  )
}
