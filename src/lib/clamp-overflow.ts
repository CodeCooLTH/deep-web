/**
 * isClampOverflowing — ข้อความที่ถูก clamp อยู่ "ยาวเกินจริงไหม"
 *
 * ใช้ตัดสินว่าจะโชว์ปุ่ม "ดูเพิ่มเติม" หรือไม่
 *
 * 🛑 ทำไมต้องวัด ไม่ใช่เดา: บทเรียนจากปุ่มกางเหรียญในไฟล์เดียวกัน (2026-08-10) — ตอนนั้นผมตั้ง
 * จำนวนตายตัวว่า "เกิน N ใบถือว่าล้น" แล้วปุ่มโผล่ตลอดทั้งที่ยังเหลือที่ว่างครึ่งแถว user ทักเอง
 * ("ต้องมีเฉพาะกรณีมันล้นสิ") — เคสข้อความก็เหมือนกันเป๊ะ: จำนวนตัวอักษรไม่ได้บอกว่าจะตก 2 บรรทัด
 * ไหม เพราะขึ้นกับความกว้างกล่อง ขนาดฟอนต์ และการตัดคำของภาษาไทยซึ่งไม่มีช่องว่างระหว่างคำ
 *
 * 🛑 `+1` กัน sub-pixel: เบราว์เซอร์ปัด `scrollHeight`/`clientHeight` เป็นจำนวนเต็มคนละทิศได้
 * ข้อความที่พอดีเป๊ะ 2 บรรทัดจึงอาจได้ scrollHeight มากกว่า clientHeight อยู่ 1px โดยไม่ได้ล้นจริง
 * ถ้าไม่เผื่อ ปุ่ม "ดูเพิ่มเติม" จะโผล่กับข้อความที่กดแล้วไม่มีอะไรเพิ่ม
 */
export function isClampOverflowing(scrollHeight: number, clientHeight: number): boolean {
  if (scrollHeight <= 0 || clientHeight <= 0) return false; // ยังวัดไม่ได้ = ยังไม่ล้น (ห้ามเดาว่าล้น)
  return scrollHeight > clientHeight + 1;
}
