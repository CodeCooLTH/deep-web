/** ข้อความไทยของ error จากการจัดการสมาชิก (EXT 00012 2026-10-05) — copy จาก ux spec
 *  ทุกข้อบอกทางออก ไม่ชวนกดซ้ำสิ่งที่ไม่มีวันผ่าน */
export function memberErrorText(code: string, name: string, primaryOwnerName: string): string {
  switch (code) {
    case 'NOT_OWNER':
      return 'การทำรายการนี้ต้องเป็นเจ้าของร้าน ถ้าบทบาทของคุณเพิ่งเปลี่ยน ให้โหลดหน้านี้ใหม่'
    case 'PRIMARY_OWNER_LOCKED':
      return `${name} เป็นเจ้าของหลัก เปลี่ยนบทบาทหรือลบไม่ได้ ถ้าอยากให้คนอื่นเป็นเจ้าของหลัก ให้เจ้าของหลักโอนความเป็นเจ้าของหลักก่อน`
    case 'CANNOT_REMOVE_SELF':
      return 'ลบตัวเองออกจากร้านไม่ได้ ถ้าไม่ดูแลร้านนี้แล้ว ให้เจ้าของคนอื่นลบคุณออก หรือเปลี่ยนตัวเองเป็นผู้ดูแล'
    case 'SHOP_LOCKED':
      return 'ร้านนี้ถูกล็อกเพราะแพ็กเกจ จึงแก้ไขทีมไม่ได้ตอนนี้ ให้เจ้าของหลักต่ออายุหรืออัปเกรดแพ็กเกจก่อน แล้วลองใหม่'
    case 'RECIPIENT_NO_PACKAGE':
      return `${name} ยังไม่มีแพ็กเกจ Business จึงรับเป็นเจ้าของหลักไม่ได้ ให้ ${name} สมัครแพ็กเกจก่อน แล้วลองโอนอีกครั้ง`
    case 'RECIPIENT_BUSINESS_QUOTA':
      return `แพ็กเกจของ ${name} มีจำนวนร้านครบโควตาแล้ว ให้ ${name} อัปเกรดแพ็กเกจก่อน แล้วลองโอนอีกครั้ง`
    case 'RECIPIENT_ADMIN_QUOTA':
      return `แพ็กเกจของ ${name} รองรับผู้ดูแลไม่พอสำหรับร้านนี้ ให้ ${name} อัปเกรดแพ็กเกจ หรือลดจำนวนผู้ดูแลของร้านนี้ก่อน แล้วลองโอนอีกครั้ง`
    case 'NOT_PRIMARY_OWNER':
      return `เฉพาะเจ้าของหลักโอนความเป็นเจ้าของหลักได้ เจ้าของหลักของร้านนี้คือ ${primaryOwnerName}`
    case 'NOT_A_MEMBER':
      return `${name} ไม่ได้อยู่ในร้านนี้แล้ว ให้โหลดหน้านี้ใหม่`
    default:
      return 'ทำรายการไม่สำเร็จ ลองอีกครั้ง ถ้ายังไม่ได้ให้โหลดหน้านี้ใหม่'
  }
}
