import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

import { describe, it, expect } from 'vitest'

const DIR = join(process.cwd(), 'src/app/(marketing)/o/[token]')

/**
 * สำนวนปิดท้ายที่อนุญาต — นอกจากนี้ถือว่าแตกแถว
 *
 * 🛑 รายการนี้เขียนจาก **ประเภทของทางออก** ไม่ใช่จากข้อความที่บังเอิญมีอยู่ตอนเขียน —
 * ตัวคัดลอกเดิมเป็นสตริงตายตัว `'กดค้างที่เลขพัสดุ…'` ⇒ พอมีปุ่มคัดลอกตัวที่สอง
 * (เลขคำสั่งซื้อ, 2026-08-28) ด่านแดงทันทีทั้งที่ข้อความใหม่ทำถูกกฎทุกตัวอักษร
 * คลาสเดียวกับ `CTA` ใน `no-payment-entry-in-app.test.ts` ที่ลิสต์คำแทนที่จะลิสต์ประเภท
 */
const ALLOWED_TAILS: (string | RegExp)[] = [
  'กรุณาลองใหม่อีกครั้ง',
  'กรุณาตรวจสัญญาณแล้วลองใหม่',
  // คัดลอกล้มเหลวไม่ใช่เรื่องที่ "ลองใหม่" แล้วจะได้ — เบราว์เซอร์ไม่ให้สิทธิ์ ต้องบอกทางที่ทำได้จริง
  // และต้อง **ระบุว่ากดค้างที่อะไร** ไม่งั้นผู้ใช้ไม่รู้ว่าต้องแตะตรงไหนบนจอที่มีเลขหลายชุด
  //
  // 🛑 regex ตัวนี้ครอบ **ทุกปุ่มคัดลอก** — เลขพัสดุ · เลขคำสั่งซื้อ · เลขบัญชี (feature 00062)
  // main เพิ่ม 'กดค้างที่เลขบัญชีเพื่อคัดลอกเองได้' เป็นสตริงตายตัวคู่กับของเดิม ซึ่งเป็นอาการ
  // เดียวกับที่ commit นี้ตั้งใจแก้พอดี (ลิสต์ข้อความ ⇒ ปุ่มตัวที่สามมาก็แดงอีก)
  // ⇒ รวมเป็น regex เดียว · ข้อความทั้งสองของ main ยังผ่านครบ ไม่ได้ผ่อนกฎอะไรลง
  /กดค้างที่\S.*เพื่อคัดลอกเองได้/,
  // feature 00062 (จาก main) — บันทึกรูป QR ล้มเหลวไม่ใช่เรื่องที่ "ลองใหม่" แล้วจะได้เช่นกัน
  // (canvas export ล้มเหลวมักเป็นข้อจำกัดของเบราว์เซอร์/อุปกรณ์ ไม่ใช่ปัญหาเครือข่ายชั่วคราว)
  // คนละประเภทกับ regex ข้างบน จึงต้องอยู่แยก
  'ลองแคปหน้าจอแทนได้',
]

function uiFiles(): string[] {
  return readdirSync(DIR).filter((f) => f.endsWith('.tsx'))
}

/** เอาเฉพาะสตริงที่ผู้ใช้เห็น — ตัดคอมเมนต์ทิ้งก่อน ไม่งั้นคอมเมนต์ที่อ้างข้อความเก่าจะถูกนับ */
function userStrings(file: string): string[] {
  const src = readFileSync(join(DIR, file), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .filter((l) => !l.trim().startsWith('//') && !l.trim().startsWith('*'))
    .join('\n')

  return [...src.matchAll(/'([^']*ไม่สำเร็จ[^']*)'/g)].map((m) => m[1])
}

describe('ข้อความล้มเหลว', () => {
  it('ทุกข้อความบอกทางไปต่อ ไม่ปล่อยให้ผู้ใช้ค้าง', () => {
    const offenders: string[] = []

    for (const f of uiFiles()) {
      for (const msg of userStrings(f)) {
        const ok = ALLOWED_TAILS.some((tail) =>
          typeof tail === 'string' ? msg.includes(tail) : tail.test(msg),
        )
        if (!ok) {
          offenders.push(`${f}: "${msg}"`)
        }
      }
    }

    expect(offenders).toEqual([])
  })

  it('ใช้สำนวนชวนลองใหม่แบบเดียว ไม่ใช่ 5 แบบ', () => {
    const variants = new Set<string>()

    for (const f of uiFiles()) {
      for (const msg of userStrings(f)) {
        const m = msg.match(/(กรุณาลอง\S*\s*\S*|ลองใหม่อีกครั้ง|ลองอีกครั้ง)$/)
        if (m) variants.add(m[1])
      }
    }

    expect([...variants]).toEqual(['กรุณาลองใหม่อีกครั้ง'])
  })
})
