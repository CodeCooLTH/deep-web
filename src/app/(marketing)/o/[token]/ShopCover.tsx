/**
 * ShopCover — ปกไล่สีตาม tier ของหน้าออเดอร์ `/o/[token]` ใช้ร่วมทั้งจอ guest และจอหลังล็อกอิน
 *
 * ทำไมไม่ใช้ `ProfileBanner` ต่อ (ตัวที่หน้าโปรไฟล์เคยใช้): มันพก 2 อย่างที่ผิดที่บนหน้านี้
 *   1. **dot-mesh overlay** — ลายจุดเป็นของประดับที่ถูกออกแบบมาสำหรับปกสูง 176–224px
 *      ย่อลงมาเหลือ 104px แล้วลายจุด 22px กลายเป็นเนื้อสัมผัสรบกวนบนแถบบาง ๆ
 *   2. **ปุ่มย้อนกลับกลม ๆ มุมซ้ายบน** — `router` ของเบราว์เซอร์พาไป "หน้าก่อนหน้า" ซึ่งสำหรับ
 *      คนที่กดลิงก์มาจากแชทคือ "กลับไปแชท" บ้าง "หน้าเปล่า" บ้าง (จริง ๆ มันเป็น Link href='/'
 *      แต่หน้าตาเป็นปุ่ม back) บนหน้าที่ผู้ซื้อยังไม่รู้ว่า Deep คืออะไร ที่ว่างมุมนั้นมีค่ากว่า
 *      ถ้าใช้บอกว่า "ใครเป็นคนรับรองหน้านี้" ⇒ แทนด้วยพิลแบรนด์ที่ทำหน้าที่เดียวกันคือกลับหน้าแรก
 *      แต่ตอบคำถามที่ผู้ซื้อถามอยู่จริงไปด้วย (แพตเทิร์นเดียวกับหน้าโปรไฟล์ร้าน)
 *
 * 🛑 **มือถือ 140px · จอกว้าง (≥861) 198px — ห้ามยกไปเท่าหน้าโปรไฟล์ (176/200/224)** — คนที่เปิดหน้านี้
 * มางานเดียวคือดูว่าออเดอร์ถึงไหนแล้วและกดยืนยัน ปกคือพื้นที่ตกแต่งล้วน ทุก px ที่ให้มันไป
 * คือ px ที่หลักฐานออเดอร์เสียไป (หน้าโปรไฟล์ต่างกันตรงที่ "ทำความรู้จักร้าน" คืองานของหน้านั้น)
 * เขียนกำกับไว้ตรงนี้เพราะเดิมสองจอตั้ง 104 กับ 140 ต่างกันอยู่แล้วโดยไม่มีเหตุผล — วันที่มีคน
 * มาไล่ "ทำให้เหมือนกัน" จะได้ไม่ไล่ขึ้นไปหาเลขของหน้าโปรไฟล์
 *
 * (2026-08-29) จอกว้างยก 104 → 160 ตอนที่ปกเริ่มแสดง **รูปจริงของร้าน** — เหตุผลเดิมยัง
 * บังคับอยู่บนมือถือ ซึ่งเป็นที่ที่ px มีค่าที่สุด (WebView ของแอปเปิดหน้านี้) ส่วนบนจอกว้าง
 * โครง 2 คอลัมน์ย่นหน้าลงมากพอที่ปกจะไม่ผลักหลักฐานลงใต้ fold
 *
 * (2026-08-30) **104 → 140 · 160 → 198 ตามม็อกอัพ v5** (`deep-order-pure-html-responsive-v5.html`
 * `.cover{height:198px}` · `@media(max-width:680px){.cover{height:140px}}`) — หัวหน้าสั่งให้
 * ทำตามม็อกอัพ · สิ่งที่แลกกลับมาไม่ใช่แค่ความสวย: **ที่ว่างบนปกกลายเป็นที่ยืนของปุ่ม
 * "ช่วยเหลือ" กับ "แชร์คำสั่งซื้อ"** (`CoverActions`) ซึ่งเดิมไม่มีที่อยู่บนหน้านี้เลย
 * ⇒ px ที่เพิ่มมาทำงาน ไม่ได้เป็นของประดับล้วนเหมือนตอนที่กฎข้างบนถูกเขียน
 * 🛑 เพดาน "ห้ามแตะเลขของหน้าโปรไฟล์ (176/200/224)" **ยังบังคับอยู่** — 198 จงใจต่ำกว่า 200
 *
 * Base: src/views/pages/user-profile/UserProfileHeader.tsx (ProfileBanner — ไล่สี tier + พิลร้านใหม่)
 *   + src/views/pages/user-profile/v2/ProfileHero.tsx (พิลตราแบรนด์บนปก)
 */
import type { ReactNode } from 'react'

import Box from '@mui/material/Box'

import { getTierGradient } from '@/lib/trust-tier'

import BrandHomeLink from './BrandHomeLink'
import { ORDER_TWO_COL_MQ } from './content-width'

/** ความสูงปกของหน้าออเดอร์ — จุดเดียวทั้งสองจอ (ดูเหตุผลที่หัวไฟล์ก่อนแก้) */
export const ORDER_COVER_HEIGHT = 140

export default function ShopCover({
  trustScore,
  /**
   * ร้านยังไม่มีออเดอร์จบสักใบ → ไล่สีเทา ไม่ใช่ไล่สี tier
   *
   * 🛑 เกณฑ์คือ "มีออเดอร์จบไหม" ไม่ใช่ trustScore — คะแนนถูกดันด้วยรีวิวเพื่อนได้ แต่ออเดอร์
   * จบจริงปลอมยากกว่ามาก (เหตุผลเต็มอยู่ที่ ProfileBanner) เดิมจอหลังล็อกอินไม่เคยส่งค่านี้เลย
   * ⇒ ร้านใหม่ได้ปกไล่สีที่หน้าตาเหมือนรางวัลทันทีที่ผู้ซื้อล็อกอิน ทั้งที่ก่อนล็อกอินเป็นเทา
   */
  isNewShop,
  coverUrl = null,
  actions = null,
}: {
  trustScore: number
  isNewShop: boolean
  /**
   * ปกที่ร้านอัปโหลดเอง (`Shop.coverImage` ผ่าน `toFileUrl` แล้ว) — `null` = ยังไม่ตั้ง ⇒ ไล่สี tier
   *
   * 🛑 ร้านตั้งปกได้มาตั้งแต่ feature 00035 (ตัวจัดหน้าร้าน) แต่หน้านี้ **ไม่เคยดึงมาใช้เลย**
   * ⇒ ร้านที่อุตส่าห์ตั้งปกไว้ ปกนั้นไม่เคยโผล่บนหน้าที่ลูกค้าเปิดดูออเดอร์
   * ม็อกอัพ `deep-full-order-page-refined.html` ใช้ **รูปถ่ายจริง** เป็นปก — ยืนยันว่านี่คือสิ่งที่ควรเป็น
   */
  coverUrl?: string | null
  /**
   * ปุ่มมุมขวาบนของปก (`CoverActions`) — ส่งเป็น node แทนที่จะ import ตรง
   *
   * 🛑 ไฟล์นี้ **ไม่ใช่ client component** และถูกใช้จากทั้งสองจอ — import ตัวที่มี `onClick`
   * เข้ามาตรง ๆ จะลากทั้งไฟล์เข้า bundle ฝั่ง client โดยไม่จำเป็น · จอไหนไม่ส่งมาก็ไม่มีปุ่ม
   */
  actions?: ReactNode
}) {
  const gradient = isNewShop
    ? 'linear-gradient(135deg, #9b98a8 0%, #bdbbc7 55%, #dedce4 100%)'
    : getTierGradient(trustScore)

  /**
   * ฉากเงาทับรูปตามม็อกอัพ (`rgba(12,9,29,.06)` → `rgba(13,10,36,.12)`)
   *
   * 🛑 จำเป็นจริง ไม่ใช่ของประดับ — พิลตราแบรนด์กับพิล "ร้านใหม่" เป็นสีอ่อนทั้งคู่
   * รูปปกที่สว่างจะกลืนจนอ่านไม่ออก (คลาสเดียวกับ `TILE_SCRIM` ที่ `DESIGN.md`
   * กำหนดไว้สำหรับตัวหนังสือที่ลอยบนรูปของผู้ใช้)
   */
  const background = coverUrl
    ? `linear-gradient(180deg, rgba(12,9,29,.06), rgba(13,10,36,.12)), url("${encodeURI(coverUrl)}")`
    : gradient

  return (
    <Box
      sx={{
        /**
         * 🛑 มือถือคง **104px** ตามกฎด้านบน — เหตุผลเดิมยังจริงทุกคำ: คนเปิดหน้านี้มางานเดียว
         * คือดูว่าออเดอร์ถึงไหน ทุก px ของปกคือ px ที่หลักฐานออเดอร์เสียไป
         *
         * จอกว้างยกเป็น **160** เพราะที่นั่นปกไม่ได้ทำให้หน้ายาวขึ้นจริง — โครง 2 คอลัมน์
         * ย่นเนื้อหาลงมากอยู่แล้ว และการ์ดออเดอร์ยังอยู่เหนือ fold ที่ 1440×900
         *
         * 🛑 **จงใจไม่ใช้ 176/200/224** ซึ่งเป็นเลขของหน้าโปรไฟล์ที่กฎด้านบนห้ามไว้ตรงตัว —
         * 198 ของม็อกอัพ v5 ผ่านเพดานนี้พอดี (ต่ำกว่า 200) จึงรับมาได้โดยไม่ต้องผ่อนกฎ
         */
        height: ORDER_COVER_HEIGHT,
        [ORDER_TWO_COL_MQ]: { height: 198 },
        position: 'relative',
        overflow: 'hidden',
        background,
        backgroundSize: 'cover',
        backgroundPosition: 'center',
      }}
    >
      {/**
       * ── แถวเครื่องมือบนปก (ม็อกอัพ v5 `.cover-tools`) ──
       *
       * 🛑 **ต้องเป็นแถวเดียวกัน** — ของเดิมต่างคนต่างวางตัวเองแบบ absolute:
       * ตราแบรนด์ยึด `top:0 left:0` แล้วเว้นระยะด้วย `p-2.5` ของตัวเอง (พิลจริงอยู่ที่ 10px)
       * ส่วนปุ่มขวายึด `top:14 right:16` และสูง 44px
       * ⇒ **ขอบบนไม่ตรงกัน ระยะห่างจากขอบซ้าย/ขวาก็ไม่เท่ากัน** (หัวหน้าเห็น 2026-08-30)
       *
       * แถว flex เดียวที่ `justify-content: space-between` ทำให้ทั้งสองฝั่งจัดกลางแนวตั้ง
       * ตรงกันเสมอ ไม่ว่าความสูงของแต่ละพิลจะต่างกันแค่ไหน และระยะขอบมาจากค่าเดียว
       */}
      <Box
        sx={{
          position: 'absolute',
          zIndex: 2,
          insetBlockStart: 4,
          insetInline: 6,
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          gap: 2,
          '@media (min-width:600px)': { insetBlockStart: 8, insetInline: 10 },
        }}
      >
        <BrandHomeLink />
        {actions}
      </Box>

      {/* พิล "ร้านใหม่" — บอกตรง ๆ ว่ายังไม่มีประวัติเพียงพอ แทนที่จะปล่อยให้ปกเทาดูเหมือนบั๊ก
          (ยกมาจาก ProfileBanner ทั้งก้อน ไม่เขียนคำใหม่ — ร้านเดียวกันต้องอ่านได้เหมือนกัน
          ไม่ว่าผู้ซื้อจะมาจากหน้าโปรไฟล์หรือจากลิงก์ออเดอร์) */}
      {isNewShop && (
        <Box
          sx={{
            position: 'absolute',
            insetInlineStart: 16,
            bottom: 12,
            display: 'inline-flex',
            alignItems: 'center',
            bgcolor: 'rgba(255,255,255,0.92)',
            backdropFilter: 'blur(8px)',
            border: '1px solid rgba(255,255,255,0.6)',
            boxShadow: 'var(--mui-customShadows-sm)',
            borderRadius: '9999px',
            px: '10px',
            py: '4px',
            /* 13px = ขั้น "Label / Caption" ของ ramp (DESIGN.md §Typography) ไม่ใช่ 12px ที่ต้นฉบับ
               ใช้ — 12px คือขั้น Overline ซึ่งสงวนไว้ให้ป้ายสั้น ๆ พร้อม letter-spacing 0.8px และ
               เอกสารระบุเองว่า "ใช้น้อยมาก" ส่วนนี่เป็นประโยคบอกสถานะเต็ม ๆ
               (ต้นฉบับใน ProfileBanner ยังเป็น 12px อยู่ = หนี้เดิม ไม่ได้แก้ในรอบนี้) */
            fontSize: '0.8125rem',
            letterSpacing: '0.4px',
            fontWeight: 600,
            color: '#2F2B3D',
          }}
        >
          ร้านใหม่ · ยังไม่มีประวัติเพียงพอ
        </Box>
      )}
    </Box>
  )
}
